# Two-pass link for the pad state-machine log: libogc's SI / PAD statics are file-local, so their addresses come from `nm` of the first link.
#   gen_padsyms.sh LOADER_DIR   (powerpc-eabi-nm, make and the devkitPPC env on PATH; the loader already built once)
# Writes LOADER_DIR/source/ms_padsyms.h, relinks, and checks the symbols did not move.  Failure leaves a working loader (all-zero header = the log says "no symbols"); exit 1 only when the relink broke or moved.
set -u
L=${1:?loader dir}
nmaddr() { powerpc-eabi-nm "$L/loader.elf" | awk -v n="$1" '$3==n && ($2 ~ /^[sdbDBgGtT]$/) {print $1; exit}'; }
gen() {
  local out="$L/source/ms_padsyms.h" a list="" n
  { echo '/* GENERATED by ota/gen_padsyms.sh: addresses of libogc statics from nm of the first link */'; echo '#define MS_PADSYM_N 9'; } > "$out.tmp"
  for n in sicntrl si_type sipacket cmdfixdevice __pad_resettingchan __pad_resettingbits __pad_pendingbits __pad_enabledbits __pad_waitingbits; do
    a=$(nmaddr $n)
    if [[ -z "$a" ]]; then echo "gen_padsyms: no symbol $n" >&2; rm -f "$out.tmp"; return 1; fi
    list="$list${list:+, }0x$a"
  done
  echo "static const volatile unsigned ms_padsym[MS_PADSYM_N] = { $list };" >> "$out.tmp"
  mv "$out.tmp" "$out"; echo "$list"
}
before=$(gen) || exit 0
touch "$L/source/update.c"
make -C "$L" > "$L/padsyms_make.log" 2>&1 || { echo "gen_padsyms: relink failed (see $L/padsyms_make.log)"; exit 1; }
after=$(gen) || exit 0
[[ "$before" == "$after" ]] || { echo "gen_padsyms: addresses moved between links ($before vs $after)"; exit 1; }
echo "gen_padsyms: $after"

/* the disc drive, before any file search: a Wii (not a Wii U / vWii, not a Wii VC) with a stock Melee disc in it launches from the drive (GamePath "di", as the loader's own 'Boot GC Disc in Drive' entry).
   The probe is the loader's own (main.c's 'di' path): DI_Init / DI_Mount, a bounded wait (4 s) for the drive that B stops, then the header of the disc (GALE01 revision 2: msdl_header_ok).  No disc, no drive
   (a console that has none), a disc that is not a GC disc or not stock all mean 'no drive disc' and the file search goes on.  SD:/multishine/no_drive_probe switches the probe off. */
static int g_drive;
static int g_drive_why;                                  /* why the last probe found no stock disc: MSST_DRV_NONE / NOTGC / NOTSTOCK (ms_start.h) */
static int drive_probe(void)
{
	u8 *b;
	u32 t0;
	int ok = 0;
	char id[7];
	mdl_u8 rev = 0;
	g_drive_why = MSST_DRV_NONE;
	if (!msst_drive_probe_allowed(IsWiiU(), isWiiVC, file_exists("sd:/multishine/no_drive_probe"))) return 0;
	DI_UseCache(false);
	DI_Init();
	DI_Mount();
	t0 = now_ms();
	{                                                                  /* bounded wait, polled every ~100 ms; the same bare 'initialising' status for 800 ms = no disc (ms_driveprobe.h) */
		struct msdp_state ps;
		int pr;
		msdp_begin(&ps);
		for (;;) {
			pr = msdp_step(&ps, (unsigned)DI_GetStatus(), (unsigned)DVD_INIT, (unsigned)(now_ms() - t0), ds_stop(0));
			if (pr != MSDP_CONTINUE) break;
			usleep(MSDP_POLL_MS * 1000);
		}
		if (pr == MSDP_STOP_NODISC) { ota_log("drive: no disc after %lu ms", (unsigned long)(now_ms() - t0)); DI_Close(); return 0; }
	}
	if (!(DI_GetStatus() & DVD_READY)) { ota_log("drive: not ready after %lu ms (no disc, no drive, or B): status %08X", (unsigned long)(now_ms() - t0), (unsigned)DI_GetStatus()); DI_Close(); return 0; }
	DI_Close();
	b = (u8 *)memalign(32, 0x800);
	if (!b) return 0;
	memset(b, 0, 0x20); DCFlushRange(b, 0x20);
	ReadRealDisc(b, 0, 0x20, DIP_CMD_NORMAL);
	if (!IsGCGame(b)) {
		memset(b, 0, 0x800); DCFlushRange(b, 0x800);
		ReadRealDisc(b, 0, 0x800, DIP_CMD_DVDR);
		if (!IsGCGame(b)) { free(b); g_drive_why = MSST_DRV_NOTGC; ota_log("drive: a disc is in, it is not a GameCube disc"); return 0; }
	}
	memcpy(id, b, 6); id[6] = 0;
	ok = msdl_header_ok((const mdl_u8 *)b, id, &rev) ? 1 : 0;
	ota_log("drive: GC disc %.6s revision %u: %s (%lu ms)", id, (unsigned)rev, ok ? "stock Melee v1.02" : "not stock", (unsigned long)(now_ms() - t0));
	free(b);
	if (!ok) g_drive_why = MSST_DRV_NOTSTOCK;
	return ok;
}

struct sdev { int has_games; int nstock; unsigned seen, places; int stopped; char first[MSGAMES_DIR_LEN]; char near[MDS_PATHLEN]; unsigned long near_size; };
static struct sdev g_dev[2];                              /* 0 = SD, 1 = USB */

static void scan_dev(int usb)                            /* the stock image of a device by the general disc search, first accepted wins (the disc lock's verdict, cache first); B stops it */
{
	static char picks[1][MSGAMES_DIR_LEN];
	struct sdev *s = &g_dev[usb];
	DIR d;
	int n;
	memset(s, 0, sizeof *s);
	if (!devices[usb ? DEV_USB : DEV_SD]) return;
	if (f_opendir_char(&d, usb ? MSGAMES_USB : MSGAMES_DIR) == FR_OK) { f_closedir(&d); s->has_games = 1; }
	n = find_discs_on(usb, 0, picks, 1, &s->seen, &s->places, &s->stopped);
	s->nstock = n;
	if (g_ds_last.near_path[0]) { strcpy(s->near, g_ds_last.near_path); s->near_size = g_ds_last.near_size; }
	ota_log("start: %s: %d stock image(s), %u of the stock size, %u places searched, %u other image(s)%s%s", usb ? "usb" : "sd", n, s->seen, s->places, g_ds_last.near, s->near[0] ? ", e.g. " : "", s->near);
	if (n > 0) { strcpy(s->first, picks[0]); s->has_games = 1; }
}


/* make the image the game to start: its path without the device, the device flag, the game id; -> 1 when that changed the saved config */
static int pick_game(int usb, const char *path)
{
	const char *q = strchr(path, ':');
	int changed;
	q = q ? q + 1 : path;
	changed = strcmp(ncfg->GamePath, q) != 0 || (((ncfg->Config & NIN_CFG_USB) != 0) != (usb != 0));
	strncpy(ncfg->GamePath, q, sizeof ncfg->GamePath);
	ncfg->GamePath[sizeof ncfg->GamePath - 1] = 0;
	memcpy(&ncfg->GameID, "GALE", 4);
	if (usb) ncfg->Config |= NIN_CFG_USB; else ncfg->Config &= ~NIN_CFG_USB;
	UseSD = !usb;
	ms_vcard_refresh();                                      /* the virtual card is looked for on the device the game now runs from */
	DCFlushRange((void *)ncfg, sizeof(NIN_CFG));
	return changed;
}

static void put_c(int y, int size, u32 color, const char *s) { PrintFormat((u8)size, color, (640 - (int)GRRLIB_WidthTTF(myFont, s, size)) / 2, y, "%s", s); }

/* s wrapped at spaces to maxw pixels, every line centred; -> the number of lines */
static int put_wrapped(int y, int size, u32 color, const char *s, int maxw)
{
	char line[160], trial[160];
	int lines = 0;
	line[0] = 0;
	for (;;) {
		const char *e = s;
		size_t wl, m = strlen(line);
		while (*e && *e != ' ') e++;
		wl = (size_t)(e - s);
		if (wl > 60) wl = 60;
		memcpy(trial, line, m);
		if (m) trial[m++] = ' ';
		memcpy(trial + m, s, wl);
		trial[m + wl] = 0;
		if (line[0] && (int)GRRLIB_WidthTTF(myFont, trial, size) > maxw) { put_c(y + lines * 20, size, color, line); lines++; memcpy(line, s, wl); line[wl] = 0; }
		else memcpy(line, trial, m + wl + 1);
		s = e;
		while (*s == ' ') s++;
		if (!*s) break;
	}
	if (line[0]) { put_c(y + lines * 20, size, color, line); lines++; }
	return lines;
}


/* draw s wrapped at spaces to maxw pixels (Aileron widths), step px between lines; -> the number of lines */
static int wrap_text(int x, int y, const char *s, u32 color, int maxw, int step, int size)
{
	char line[200], trial[200];
	size_t n = 0, wl, m;
	int lines = 0;
	line[0] = 0;
	for (;;) {
		const char *e = s;
		while (*e && *e != ' ') e++;
		wl = (size_t)(e - s);
		if (wl > 80) wl = 80;
		m = n;
		memcpy(trial, line, n);
		if (m) trial[m++] = ' ';
		memcpy(trial + m, s, wl);
		trial[m + wl] = 0;
		if (n && (int)GRRLIB_WidthTTF(myFont, trial, size) > maxw) {            /* this word does not fit: print the line, start the next with it */
			PrintFormat(size, color, x, y + lines * step, "%s", line);
			lines++;
			memcpy(line, s, wl); line[wl] = 0; n = wl;
		} else { memcpy(line, trial, m + wl + 1); n = m + wl; }
		s = e;
		while (*s == ' ') s++;
		if (!*s) break;
	}
	if (n) { PrintFormat(size, color, x, y + lines * step, "%s", line); lines++; }
	return lines;
}


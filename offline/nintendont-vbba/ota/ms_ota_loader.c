void ms_main_crumb(const char *what)
{
	if (ms_chain_marker()) ota_log("chain: main: %s", what);
}

void ms_ota_alive_early(void)
{
	if (!ms_chain_marker()) return;
	g_confirm_after_pads = 1;
	if (MountDevice(DEV_SD)) {
		int had = file_exists(MSOTA_SHL_OK);
		if (had) unlink_path(MSOTA_SHL_OK);                                  /* shl.ok is the OLD shell's; this shell writes its own once the pads are up (a crash before that leaves none: the stub counts it) */
		ota_log("chain: hand-over alive at main(): the very first action of the new shell (SD mounted; guard word read and cleared; shl.ok of the old shell %s)", had ? "removed" : "absent");
		FlushDevices();
	}
}

/* called by main BEFORE the loader patches and reloads IOS58: the Homebrew Channel's own IOS and network state, where the Wii's network works.  The same check as the one in
   ms_ota_select (which then skips it), with SD mounted and unmounted around it. */
void ms_ota_precheck(void)
{
#if !defined(MS_OTA_MODE_NOSD) && !defined(MS_OTA_MODE_NONET)
	struct msota_state st;
	static int pad_inited;
	if (!pad_inited) { PAD_Init(); pad_inited = 1; }                   /* hold B on a GameCube pad skips the wait (the Wii remotes are not up yet) */
	if (!MountDevice(DEV_SD)) { ota_log("precheck: the SD card could not be mounted (no card, a card that cannot be read, or the loader started from USB): nothing can be written to SD:/multishine, the log stays in RAM"); ota_net_abort(); return; }
	load_state(&st);
	ota_log_start(&st);
	ota_log("precheck: before the IOS58 reload");
	{ extern void ms_pad_diag(const char *); ms_pad_diag("precheck start"); }
	{ extern void ms_inject_prev_status(void); ms_inject_prev_status(); }
	ota_early = 1;
	if (file_exists(MSOTA_CHAIN_TRY) && !ms_chain_marker()) {            /* an earlier hand-over never confirmed: never again */
		unsigned fails = chain_fail_count() + 1;
		ota_log("chain: chain.try is left from a hand-over that never came alive (failure %u in a row): the hand-over is switched off (no_chain written); the update texts say 'starts the next time'", fails);
		write_file(MSOTA_NO_CHAIN, (const u8 *)"1", 1);
		chain_fail_set(fails);
		unlink_path(MSOTA_CHAIN_TRY);
	} else if (file_exists(MSOTA_CHAIN_TRY)) {
		char rep[200];
		ota_log("chain: this start is the hand-over of the previous shell (marker present)");
		chain_fail_set(0);                                                                            /* it came alive: the failure count starts again */
		if (ms_chain_report(rep, sizeof rep)) ota_log("chain: %s", rep);
		else ota_log("chain: no tramp report in memory (the tramp did not run to its end)");
		unlink_path(MSOTA_CHAIN_TRY);                                                                 /* this shell is alive (video, SD, precheck): chain.try is done, so THIS start may hand over again */
		ota_log("chain: hand-over confirmed (alive at the precheck); chain.try cleared, a newer shell found below may be chained to");
	}
	if (!file_exists("sd:/multishine/ota_off")) {
		precheck_netfail = 0;
		ota_boot_check(&st);
		precheck_done = precheck_netfail == 2 ? 0 : 1;
	}
	ota_chain_after_check();                                           /* a shell was installed: restart into it (hand-over in place), or say plainly what to do */
	{ extern void ms_pad_diag(const char *); ms_pad_diag("precheck end"); }
	ota_early = 0;
	ota_net_abort();                                                   /* the IOS reload follows: an unused (or still busy) init must not run across it */
	FlushDevices();
	UnmountDevice(DEV_SD);
#endif
}

void ms_ota_select(void **zip, unsigned int *zip_len)
{
	struct msota_state st;
	struct msota_kernel k;
	u8 *file = NULL;
	u32 flen = 0;
	int file_ok = 0, pick, action = 0, confirmed, r;
	*zip = NULL; *zip_len = 0;
	{ extern void ms_pad_diag(const char *); ms_pad_diag("game start"); }
	if (*(volatile const char *)ms_shell_seq_tag != 'M') return;          /* never true: keeps the sequence tag linked in (the linker drops unreferenced data) */
#ifdef MS_OTA_MODE_NOSD
	trail("no-sd");                                                       /* diagnostic builds A: not one SD or network access before the kernel (the stock loader flow) */
	return;
#endif
	trail("sd?");
	if (!MountDevice(DEV_SD)) { gprintf("OTA: no SD card, embedded kernel\r\n"); ota_log("select: the SD card could not be mounted: embedded kernel, no log file"); trail("nosd"); return; }
	trail("sd-ok");
	if (!ms_chain_marker()) write_file(MSOTA_SHL_OK, (const u8 *)"1", 1);      /* a hand-over start confirms itself only after FPAD_Init (ms_ota_pads_ready) */
	else g_confirm_after_pads = 1;
	if (file_exists(MSOTA_CHAIN_TRY)) { unlink_path(MSOTA_CHAIN_TRY); chain_fail_set(0); ota_log("chain: hand-over confirmed (alive after the IOS58 reload)"); }                         /* the stub's evidence that this shell started: a downloaded shell that never gets here is dropped */
	load_state(&st);
	ota_log_start(&st);
#ifndef MS_OTA_MODE_NONET
	soak_maybe_run("game start");                                      /* autoboot path: the soak keeps the loader here */
#endif
#ifdef MS_OTA_MODE_NONET
	trail("net-off");                                                     /* diagnostic builds B: the SD step only */
#else
	{   /* the marker SD:/multishine/ota_off skips the boot check (and with it all network code) without a rebuild */
		if (file_exists("sd:/multishine/ota_off")) trail("ota_off");
		else if (precheck_done) trail("chk-early");                                         /* done before the IOS58 reload (ms_ota_precheck), with the network started first of all */
		else { trail("chk?"); ota_boot_check(&st); trail("chk-ok"); if (inst_shell_seq) { g_chain_after_pads = 1; ota_log("restart: shell %lu installed after the IOS58 reload, before the kernel: the hand-over waits until the kernel runs and the pads are up", (unsigned long)inst_shell_seq); } }   /* may install a newer kernel / shell; a new shell is handed over to after the kernel load and FPAD_Init (ms_pads_confirm_and_chain), the kernel decision below sees the new kernel.bin */
	}
#endif
	if (MS_VUSB() && devices[DEV_USB]) card_boot_apply();                 /* a virtual card on USB is only readable here (the early check has the SD card alone) */
	r = read_file(MSOTA_KBIN, &file, &flen, MSOTA_MAX_FILE);
	if (r == 0) {
		r = msota_check(file, flen, ms_ota_pubs, MS_OTA_NPUB, 1, &k);
		file_ok = (r == MSOTA_OK);
		if (!file_ok) gprintf("OTA: kernel.bin refused: %s\r\n", msota_err(r));
	}
	confirmed = st.pending ? prev_run_reached_game() : 0;
	pick = msota_decide(&st, file_ok, file_ok ? k.seq : 0, confirmed, &action);
	if (action == 1) {                                     /* two starts without reaching the game: this kernel is out */
		unlink_path(MSOTA_KBAD);
		rename_path(MSOTA_KBIN, MSOTA_KBAD);
		gprintf("OTA: kernel %u rolled back (kernel.bad), embedded kernel\r\n", (unsigned)st.bad);
	}
	if (file_ok || st.floor || st.pending || action) save_state(&st);
	if (pick == MSOTA_PICK_DOWNLOADED) {
		void *copy = memalign(32, (k.zip_len + 31u) & ~31u);
		if (copy) { memcpy(copy, k.zip, k.zip_len); *zip = copy; *zip_len = k.zip_len; gprintf("OTA: kernel %u from the SD card (pending %d)\r\n", (unsigned)k.seq, (int)st.pending); }
	}
	if (file) free(file);
	FlushDevices();
	UnmountDevice(DEV_SD);
	trail(pick == MSOTA_PICK_DOWNLOADED ? "krn=sd" : "krn=emb");
	trail("sd-down");
}



/* after a failure screen: A send / B skip / Y never ask again */
static void diag_offer(const char *reason)
{
	char result[96] = "";
	u32 color = BLACK;
	bool redraw = true;
	u64 delay = ticks_to_millisecs(gettime()) + 600;
	if (diag_muted()) return;
	for (;;) {
		if (redraw) {
			int y = MENU_POS_Y + 36;
			ClearScreen();
			ms_title("Send a problem report?");
			if (g_last_bad[0]) { PrintFormat(DEFAULT_SIZE, MAROON, MENU_POS_X, y, "%.64s", g_last_bad); y += 26; }
			y = diag_blurb(y);
			diag_status_lines(y, result, color);
			ms_foot(0, "B", "Skip", "A", "Send", "Y", "Never ask", NULL);
			UpdateScreen();
			ClearScreen();
			redraw = false;
		}
		VIDEO_WaitVSync();
		FPAD_Update();
		if (delay > ticks_to_millisecs(gettime())) continue;
		if (FPAD_OK(0)) {
			diag_do_send(reason, result, sizeof result, &color);
			if (color == BLACK) { ClearScreen(); diag_status_lines(MENU_POS_Y + 120, result, color); UpdateScreen(); sleep(3); ClearScreen(); return; }
			redraw = true; delay = ticks_to_millisecs(gettime()) + 600;
		}
		else if (FPAD_Y(0)) { write_file(MSOTA_DIAG_NO, (const u8 *)"1", 1); return; }
		else if (FPAD_Cancel(0)) return;
	}
}

static int ms_reset_screen(void)
{
	struct msr_ui u;
	char line[96] = "";
	u32 color = MAROON;
	int redraw = 1;
	u64 delay = ticks_to_millisecs(gettime()) + 400;
	if (!devices[DEV_SD]) MountDevice(DEV_SD);
	msr_ui_begin(&u);
	for (;;) {
		int ev;
		if (redraw) { ClearScreen(); rs_draw(&u, line, color); UpdateScreen(); ClearScreen(); redraw = 0; }
		VIDEO_WaitVSync();
		FPAD_Update();
		if (delay > ticks_to_millisecs(gettime())) continue;
		ev = msr_ui_frame(&u, FPAD_Up(0) ? 1 : 0, FPAD_Down(0) ? 1 : 0, FPAD_Cancel(0) ? 1 : 0, FPAD_OK(0) ? 1 : 0, FPAD_OK(1) ? 1 : 0, (unsigned)ticks_to_millisecs(gettime()));
		if (ev == MSR_REDRAW) redraw = 1;
		else if (ev == MSR_EXIT) return 0;
		else if (ev == MSR_GO) {
			struct msr_ops o;
			struct msr_result r;
			int rc;
			if (!devices[DEV_SD]) { snprintf(line, sizeof line, "No SD card. Nothing was changed."); color = MAROON; msr_ui_begin(&u); redraw = 1; continue; }
			rs_message("Reset Multishine", "Removing...", BLACK);
			o.ctx = NULL; o.exists = rs_exists; o.rename = rs_rename; o.remove = rs_remove; o.mkdir = rs_mkdir; o.log = rs_log;
			ota_log("reset: started by the player (hold A)");
			rc = msr_run(&o, &r);
			ota_log("reset: result %d: %d moved, %d deleted, %d failed, %d absent", rc, r.moved, r.deleted, r.failed, r.absent);
			if (rc == MSR_OK) {
				rs_ram_defaults();
				rs_message("Reset Multishine", MSR_TXT_DONE, BLACK);
				{ const u64 t = ticks_to_millisecs(gettime()) + 1800; while (ticks_to_millisecs(gettime()) < t) { VIDEO_WaitVSync(); FPAD_Update(); } }
				return 1;
			}
			msr_fail_text(line, sizeof line, &r);
			color = MAROON;
			if (rc == MSR_PARTIAL) rs_ram_defaults();               /* what could be removed is gone: the session's settings follow it, so nothing stale is saved over the new set-up */
			msr_ui_begin(&u);
			redraw = 1;
			delay = ticks_to_millisecs(gettime()) + 400;
		}
	}
}


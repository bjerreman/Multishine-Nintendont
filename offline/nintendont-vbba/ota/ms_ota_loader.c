extern int ms_chain_marker(void);
extern int ms_chain_late(void);
extern vu32 KernelLoaded;                 /* main.c: the Nintendont kernel was loaded by this shell, or answered the probe after a late hand-over */
extern void *ms_chain_alloc2(u32 size);
extern int ms_chain_run(const u8 *dol, u32 len, int argc, char **argv, const struct ms_chain_hooks *hk);
extern int ms_chain_report(char *out, unsigned n);
static int saved_argc;
static char **saved_argv;
void ms_ota_args(int argc, char **argv) { saved_argc = argc; saved_argv = argv; }

static unsigned chain_fail_count(void)                                    /* hand-overs that never came alive, in a row (0 when the file is absent) */
{
	u8 *b = NULL;
	u32 n = 0;
	unsigned c = 0;
	if (read_file(MSOTA_CHAIN_FAIL, &b, &n, 16) == 0) { if (n >= 1) c = b[0]; free(b); }
	return c;
}
static void chain_fail_set(unsigned c) { u8 b = (u8)(c > 200 ? 200 : c); if (c) write_file(MSOTA_CHAIN_FAIL, &b, 1); else unlink_path(MSOTA_CHAIN_FAIL); }

static void chain_crumb(const char *t) { ota_log("%s", t); }          /* a breadcrumb: one line of ota.log, written while the SD is still mounted */
static void chain_shutdown(void) { ota_log("chain: SD and USB closed, the tramp runs now (the log ends here)"); FlushDevices(); CloseDevices(); }

/* after a shell was installed (the early check, the manual Update screen, the About check): RESTART into it, by itself, no button (design rule), by the in-place hand-over, DEFAULT ON, no marker.
   Teardown = AUDIO_StopDMA, VIDEO_Flush, GX_Flush with a breadcrumb before and after each (ms_chain_steps.h); the tramp (ms_tramp2.S) masks the interrupts, verifies its copy and reports.  Late (menu up) the
   machine is prepared: network down, Wii remotes off, devices closed; the IOS is left as it is (a clean IOS reload switches AHB protection on and the new shell's main would hang).  Self-protection: chain.try is written before the jump and removed by the new shell
   once it is alive; a start that finds it left over writes no_chain by itself and counts the failure in chain.fail (two in a row = never again, even if no_chain is removed); no_chain, the failure count,
   the loop guard word, a file that does not verify, a refused DOL or buffer all give the calm words 'It starts the next time you open Nintendont.' instead (the word 'restarting' is shown only when the
   restart really starts).  Dev: SD:/multishine/reboot = STM_RebootSystem, SD:/multishine/teardown_full = every teardown step.  Returns whenever no restart happened. */
static void ota_chain_after_check(void)
{
	struct msota_chain_in in;
	struct msota_restart_in ri;
	struct msota_shell sh;
	struct msdol_plan plan;
	struct ms_chain_hooks hk = { chain_crumb, chain_shutdown, 0, (KernelLoaded || ms_chain_late()) ? 1 : 0 };   /* LATE only when the kernel runs (or this start was itself a late hand-over: IOS58 is patched); 170 used !ota_early and also sent LATE from ms_ota_select, before its kernel load */
	u8 *file = NULL, *dolbuf = NULL;
	u32 flen = 0;
	int ce = -1, d = MSOTA_CH_NOINST, rs;
	char msg[80];
	if (!inst_shell_seq) return;
	memset(&in, 0, sizeof in); memset(&ri, 0, sizeof ri);
	in.installed = 1; in.early = ota_early; in.reload_ok = 1; in.marker = file_exists(MSOTA_CHAIN_TRY); in.disabled = file_exists(MSOTA_NO_CHAIN) || chain_fail_count() >= 2;       /* no_chain, or two failed hand-overs in a row: never retried */
	ri.installed = 1; ri.reboot_ok = 1; ri.reboot_marker = file_exists(MSOTA_REBOOT);
	if (read_file(MSOTA_SHL_BIN, &file, &flen, MSOTA_MAX_SHELL_FILE) == 0) {
		ce = msota_check_shell(file, flen, ms_ota_pubs, MS_OTA_NPUB, 1, &sh);                               /* the installed file, checked again from the card */
		in.verified = ri.verified = (ce == MSOTA_OK && sh.seq == inst_shell_seq);
	}
	if (in.verified && !ri.reboot_marker && !in.marker && !in.disabled) {                                    /* the in-place hand-over (default): stage the verified DOL */
		in.dol_ok = msdol_check(sh.dol, sh.dol_len, &plan) == MSDOL_OK;
		if (in.dol_ok) {
			dolbuf = (u8 *)ms_chain_alloc2(sh.dol_len);
			in.mem2_ok = dolbuf != NULL;
			if (dolbuf) {
				memcpy(dolbuf, sh.dol, sh.dol_len); DCFlushRange(dolbuf, sh.dol_len);
				if (memcmp(dolbuf, sh.dol, sh.dol_len) != 0) in.mem2_ok = 0;                            /* the staging copy must equal the verified DOL */
			}
		}
		if (ms_chain_marker() && !in.marker) ota_log("chain: this start is a hand-over; chaining to the next shell");        /* a chain of hand-overs: each one installs a strictly newer shell, chain.try / chain.fail / no_chain bound it */
		d = msota_chain_decide(&in);
	}
	ri.inplace_ok = (d == MSOTA_CH_GO);
	rs = msota_restart_decide(&ri);
	ota_log("restart: shell %lu installed (%s); verified %d (check %d); reboot marker %d; failed hand-overs in a row %u; chain decision %s -> %s", (unsigned long)inst_shell_seq, ota_early ? "early" : KernelLoaded ? "late: the kernel runs, the menu is up" : "after the IOS58 reload, before the kernel", ri.verified, ce,
	        ri.reboot_marker, chain_fail_count(), d != MSOTA_CH_NOINST ? msota_chain_name(d) : "not asked",
	        rs == MSOTA_RS_REBOOT ? "console restart (dev marker)" : rs == MSOTA_RS_INPLACE ? "in-place hand-over" : rs == MSOTA_RS_BAD ? "installed file does not verify" : "no restart: starts next time");
	if (rs == MSOTA_RS_INPLACE) {
		snprintf(msg, sizeof msg, "Updated. Restarting...");       /* shown only here: the restart is really started below */
		ShowMessageScreen(msg);
		write_file(MSOTA_CHAIN_TRY, (const u8 *)"1", 1);
		ota_log("chain: chain.try written (%s)", !hk.late ? "early: no IOS reload" : "late: network down, Wii remotes off, devices closed, no IOS reload");
		ota_net_down();
		FlushDevices();
		hk.full = file_exists(MSOTA_TEARDOWN_FULL);
		if (hk.full) ota_log("chain: teardown_full marker: every teardown step is run (dev)");
		if (hk.late) {
			/* NO clean IOS reload (late path: black screen after the tramp): a stock reload switches AHB protection back on and drops the IOS patches the loader made at its start; the new
			   shell's main() expects the Homebrew Channel's state (protection off) or the state its own reload leaves.  The running IOS (already reloaded and patched by this shell) is left as it is. */
			ota_log("chain: step 0: WPAD_Shutdown, close the SD and USB; the IOS is left as it is (no reload)");
			WPAD_Shutdown();
			CloseDevices();
			MountDevice(DEV_SD);                                                                      /* the log goes on: crumbs of the steps after */
			ota_log("chain: step 0 done: SD mounted again");
		}
		ms_chain_run(dolbuf, sh.dol_len, saved_argc, saved_argv, &hk);                                  /* never returns unless the DOL was refused */
		if (!devices[DEV_SD]) MountDevice(DEV_SD);
		unlink_path(MSOTA_CHAIN_TRY);
		ota_log("chain: the hand-over was refused before the tramp ran");
	} else if (rs == MSOTA_RS_REBOOT) {
		snprintf(msg, sizeof msg, "Updated. Restarting the Wii...");
		ShowMessageScreen(msg);
		usleep(2500 * 1000);
		ota_log("restart: closing the network and the SD, STM_RebootSystem (the log ends here)");
		ota_net_down();
		FlushDevices();
		CloseDevices();
		STM_RebootSystem();
		usleep(2000 * 1000);
		MountDevice(DEV_SD);
		ota_log("restart: STM_RebootSystem returned: no restart");
	}
	if (rs == MSOTA_RS_BAD) snprintf(msg, sizeof msg, "Update failed its check. Not used.");
	else snprintf(msg, sizeof msg, "Updated. It starts next time.");
	ShowMessageScreen(msg);
	usleep(2500 * 1000);
	if (file) free(file);
}

/* main()'s very first action: when this start is a hand-over, mount the SD and write the first line at once (before Initialise, the network, the IOS reload) */
/* from ms_ota_pads_ready (right after FPAD_Init + the first FPAD_Update): a hand-over start writes its shl.ok here (the stub's evidence that this shell works), and a shell installed by the check
   inside ms_ota_select (before the kernel) is handed over to here, now a true late hand-over: the kernel runs, the pads are up (the same state as the About screen's manual check) */
static void ms_pads_confirm_and_chain(void)
{
	if (g_confirm_after_pads && devices[DEV_SD]) {
		g_confirm_after_pads = 0;
		write_file(MSOTA_SHL_OK, (const u8 *)"1", 1);
		FlushDevices();
		ota_log("chain: hand-over start alive after FPAD_Init and the first pad read: shl.ok written");
	}
	if (g_chain_after_pads) {
		g_chain_after_pads = 0;
		ota_log("restart: the kernel runs and the pads are up: the hand-over to shell %lu now (late)", (unsigned long)inst_shell_seq);
		ota_chain_after_check();
	}
}

int ms_ota_late_kernel(void)
{
	/* called by main instead of the kernel load when the old shell flagged the hand-over LATE.  1 = the Nintendont kernel answered the probe (it runs: the kernel load is skipped);
	   0 = nobody answered (hands over from ms_ota_select, after the IOS58 reload but BEFORE its kernel load): main() then goes on with ms_ota_select and the kernel load as on any start.
	   shl.ok is NOT written here: ms_ota_pads_ready does it once FPAD_Init and FPAD_Update ran. */
	extern int ms_kernel_alive(void);
	int alive = ms_kernel_alive();
	g_confirm_after_pads = 1;
	if (!MountDevice(DEV_SD)) return alive;
	if (file_exists(MSOTA_CHAIN_TRY)) { unlink_path(MSOTA_CHAIN_TRY); chain_fail_set(0); }
	if (alive) ota_log("chain: late hand-over: IOS already reloaded and patched, the Nintendont kernel answered the probe (it runs): IOS reload, IOS patches and kernel load skipped; shl.ok follows once the pads are up");
	else ota_log("chain: late hand-over flag but no kernel answered the probe (the old shell handed over before its kernel load): IOS reload and patches skipped, the kernel is loaded now");
	FlushDevices();
	UnmountDevice(DEV_SD);
	return alive;
}


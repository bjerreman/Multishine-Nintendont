/* download file number `seq`, verify, write NEW, read it back and verify again, swap it in (the previous file stays as BAK).  skip lets the user abort.  -> OU_* ; *got = installed seq */
static int ota_install(const struct ota_kind *K, u32 seq, u32 min_seq, u32 deadline_ms, int (*skip)(void), u32 *got)
{
	char path[96];
	u8 *buf = NULL, *chk = NULL;
	u32 n = 0, status = 0, clen = 0, s2 = 0;
	int r;
	if (skip && skip()) { ota_log("install %s %lu: skipped by the user", K->route, (unsigned long)seq); return OU_SKIPPED; }
	snprintf(path, sizeof path, "/v1/update/%s/%lu", K->route, (unsigned long)seq);
	g_why[0] = 0;
	if (g_last_size) {                                                  /* the server announced the size: is there room before 7 s of download? */
		u32 fr = 0;
		int fe = sd_free_bytes(&fr);
		if (fe == 0 && msota_space_ok(fr, g_last_size)) { msota_fmt_full(g_why, sizeof g_why, fr, g_last_size); ota_log("install %s %lu: %s (announced size %lu)", K->route, (unsigned long)seq, g_why, (unsigned long)g_last_size); return OU_FULL; }
	}
	r = ota_get(path, K->max_file, deadline_ms, &buf, &n, &status);
	if (r != 0) { ota_log("install %s %lu: download failed", K->route, (unsigned long)seq); return OU_DOWNLOAD; }
	r = K->check(buf, n, min_seq ? min_seq : 1, &s2);
	g_chk_err = r;
	if (r != MSOTA_OK) { ota_log("install %s %lu: refused (%d %s), %lu bytes, floor %lu", K->route, (unsigned long)seq, r, msota_err(r), (unsigned long)n, (unsigned long)min_seq); free(buf); return OU_REFUSED; }
	f_mkdir_char(MSOTA_DIR);
	{                                                                   /* room for it? the exact size is known now */
		u32 fr = 0;
		int fe = sd_free_bytes(&fr);
		ota_log("install %s %lu: %lu bytes downloaded, SD free %lu bytes (f_getfree rc %d)", K->route, (unsigned long)seq, (unsigned long)n, (unsigned long)fr, fe);
		if (fe == 0 && msota_space_ok(fr, n)) { msota_fmt_full(g_why, sizeof g_why, fr, n); ota_log("install %s %lu: %s", K->route, (unsigned long)seq, g_why); free(buf); return OU_FULL; }
	}
	if (file_exists(K->knew)) ota_log("install %s %lu: %s was left by an earlier cut start, removing it", K->route, (unsigned long)seq, K->knew);
	unlink_path(K->knew);
	g_wstep[0] = 0;
	if (write_file(K->knew, buf, n) != 0) {
		snprintf(g_why, sizeof g_why, "%s", g_wstep[0] ? g_wstep : "write failed");
		ota_log("install %s %lu: SD write failed (%s)", K->route, (unsigned long)seq, g_why);
		free(buf); unlink_path(K->knew);
		return OU_WRITE;
	}
	{                                                                   /* read it back through a fresh open and check the whole container again */
		int rr = read_file(K->knew, &chk, &clen, K->max_file), ce = 0;
		const char *why = NULL;
		if (rr != 0) { snprintf(g_why, sizeof g_why, "read-back failed, code %d", rr); why = g_why; }
		else if (clen != n) { snprintf(g_why, sizeof g_why, "read-back size %lu, written %lu", (unsigned long)clen, (unsigned long)n); why = g_why; }
		else if ((ce = K->check(chk, clen, 1, &s2)) != MSOTA_OK) { snprintf(g_why, sizeof g_why, "check %d %s", ce, msota_err(ce)); g_chk_err = ce; why = g_why; }
		else if (memcmp(chk, buf, n) != 0) { u32 d = 0; while (d < n && chk[d] == buf[d]) d++; snprintf(g_why, sizeof g_why, "bytes differ at %lu", (unsigned long)d); why = g_why; }
		if (why) {
			ota_log("install %s %lu: the written file did not verify (%s)", K->route, (unsigned long)seq, why);
			if (chk) free(chk);
			free(buf);
			unlink_path(K->knew);
			return OU_VERIFY;
		}
	}
	free(buf);
	free(chk);
	unlink_path(K->bak);
	{
		static const struct msota_fs fs = { NULL, fs_exists, fs_unlink, fs_rename, fs_create };
		int sw = msota_swap_in(&fs, K->bin, K->knew, K->bak);
		if (sw != MSOTA_SW_OK) { ota_log("install %s %lu: swap failed (%s)", K->route, (unsigned long)seq, sw == MSOTA_SW_BAK ? "the old file could not be moved aside" : "the new file could not be moved in"); return OU_WRITE; }
	}
	FlushDevices();
	*got = s2;
	ota_log("install %s %lu: installed (%lu bytes)", K->route, (unsigned long)s2, (unsigned long)n);
	return OU_INSTALLED;
}

/* the shell's rollback state is the STUB's: read it for the floor (the highest shell sequence ever started), never write it */
static u32 shell_have(void)
{
	struct msota_state st;
	u8 *b = NULL;
	u32 n = 0, have = MS_SHELL_SEQ;
	msota_state_init(&st);
	if (read_file(MSOTA_SHL_ST, &b, &n, 4096) == 0) { if (!msota_state_parse(&st, b, n)) msota_state_init(&st); free(b); }
	if (st.floor > have) have = st.floor;
	return have;
}

static u32 chk_next(void)                                  /* the "next allowed check" epoch, 0 = none */
{
	u8 *b = NULL;
	u32 n = 0, v = 0, i;
	if (read_file(MSOTA_CHK, &b, &n, 64) != 0) return 0;
	for (i = 0; i + 5 < n && !(b[i] == 'n' && b[i + 1] == 'e' && b[i + 2] == 'x' && b[i + 3] == 't' && b[i + 4] == ' '); i++) {}
	if (i + 5 < n) { i += 5; while (i < n && b[i] >= '0' && b[i] <= '9') { v = v * 10 + (u32)(b[i] - '0'); i++; } }
	free(b);
	return v;
}

static void chk_set(u32 next)
{
	char t[40];
	snprintf(t, sizeof t, "next %lu\n", (unsigned long)next);
	ota_log("back-off %s", next ? t : "cleared (next 0)");
	f_mkdir_char(MSOTA_DIR);
	write_file(MSOTA_CHK, (const u8 *)t, (u32)strlen(t));
}


/* ---- Connection check: the player's OWN link, measured from the loader at every boot, no contact with our server.  UDP DNS queries for "localhost" to the
   gateway (a guess: the network's .1, like the DNS code above; libogc's if_config would run DHCP again), then 1.1.1.1 / 8.8.8.8 (ms_probe_core.c has the ladder, the statistics and the verdict).  Runs inside the boot
   check after the updates and before the network goes down, only with the network up; SD:/multishine/no_conn_check switches it off; hold B skips it.  Never longer than CONN_DURATION_US + CONN_SLACK_US. ---- */
#define MSCONN_OFF "sd:/multishine/no_conn_check"
#define MSCONN_ON  "sd:/multishine/conn_check_on"   /* since neither the check nor the Wi-Fi network window needs this marker (a leftover file is harmless).  Was OPT-IN until a Wii had run it: the early check's UDP DNS lost the GameCube pads in (dns_on is opt-in for that reason); this probe also sends and receives UDP in that window */
#define MSCONN_TXT "sd:/multishine/conn.txt"
#define CONN_DURATION_US 4000000u                 /* 10 s on the deciding leg (the core's default is 20 s: this runs at every boot) */
#define CONN_SLACK_US    3000000u                  /* hard limit for the whole check: duration + 3 s, whatever the sockets do */
static int conn_ran, conn_hint;
static struct msp_ladder g_probe;
static u32 conn_us(void) { return (u32)ticks_to_microsecs(gettime()); }
static void conn_screen(const char *const *ln, int n)
{
	int w, k, i;
	for (k = 0; k < 2; k++) {                                          /* both frame buffers */
		ClearScreen();
		for (i = 0; i < n; i++) {
			w = (int)GRRLIB_WidthTTF(myFont, ln[i], DEFAULT_SIZE);
			PrintFormat(DEFAULT_SIZE, BLACK, (640 - w) / 2, 232 - (n - 1) * 12 + i * 24, "%s", ln[i]);
		}
		GRRLIB_Render();
	}
	ClearScreen();
}
/* the Wii's stored network config, READ ONLY (ncd/manage ioctlv 3, the call Nintendont's own main.c makes before its profile write; the write, ioctlv 4, is never made here): the kind of connection the
   game will use (Nintendont's Network Profile 1-3, or on Auto the Wii's selected one) and the kind IOS brings up.  MSP_NET_UNKNOWN when anything fails. */
static int conn_profile_kind(u32 profile, int *link, int *rc_out)
{
	enum { CFG_LEN = 0x1B5C, CFG_ST = 0x1B60, CFG_TOT = 0x1B80 };
	ioctlv *cv = (ioctlv *)memalign(32, sizeof(ioctlv) * 2);
	u8 *cb = (u8 *)memalign(32, CFG_TOT);
	int kind = MSP_NET_UNKNOWN;
	s32 fd, rc = -1;
	*link = MSP_NET_UNKNOWN;
	if (cv && cb) {
		memset(cb, 0, CFG_TOT);
		cv[0].data = cb; cv[0].len = CFG_LEN; cv[1].data = cb + CFG_ST; cv[1].len = 0x20;
		DCFlushRange(cb, CFG_TOT); DCFlushRange(cv, sizeof(ioctlv) * 2);
		fd = IOS_Open("/dev/net/ncd/manage", 0);
		if (fd >= 0) {
			rc = IOS_Ioctlv(fd, 3, 0, 2, cv);
			IOS_Close(fd);
			DCInvalidateRange(cb, CFG_TOT);
			if (rc >= 0 && *(u32 *)(cb + CFG_ST) == 0) kind = msp_cfg_kind(cb, CFG_LEN, profile, link);
			else rc = rc < 0 ? rc : -9999;
		} else rc = fd;
	}
	if (cv) free(cv);
	if (cb) free(cb);
	*rc_out = (int)rc;
	return kind;
}
/* Nintendont's Network Profile (0 Auto, 1-3) straight from the settings file: the loader's own copy of the settings is not reliable this early (the 130 test logged row 0 while the file said 1) */
static u32 file_net_profile(void)
{
	u8 *b = NULL;
	u32 len = 0, p = 0;
	if (read_file("sd:/multishine/nincfg.bin", &b, &len, 4096) == 0 && b) {
		if (len >= 548 && b[0] == 0x01 && b[1] == 0x07 && b[2] == 0x0C && b[3] == 0xF6) p = b[543] & 3u;
		free(b);
	}
	return p;
}
/* Select the chosen network profile in the Wii's stored config BEFORE the network is brought up, exactly the edit Nintendont's main.c makes at game launch (enable the profile, disable the other two,
   wired/wireless select), so the update check uses the same connection the game will (: the Wii's own selection was a cable with nothing plugged in, "no network" at every boot).  Nothing is
   written when the config already says that. */
static void conn_apply_profile(u32 profile)
{
	enum { CFG_LEN = 0x1B5C, CFG_ST = 0x1B60, CFG_TOT = 0x1B80 };
	ioctlv *cv = (ioctlv *)memalign(32, sizeof(ioctlv) * 2);
	u8 *cb = (u8 *)memalign(32, CFG_TOT), *orig = (u8 *)malloc(0x1C00);
	s32 fd, rc = -1, wr = 0;
	if (profile < 1 || profile > 3) { if (cv) free(cv); if (cb) free(cb); if (orig) free(orig); return; }
	if (cv && cb && orig) {
		memset(cb, 0, CFG_TOT);
		cv[0].data = cb; cv[0].len = CFG_LEN; cv[1].data = cb + CFG_ST; cv[1].len = 0x20;
		DCFlushRange(cb, CFG_TOT); DCFlushRange(cv, sizeof(ioctlv) * 2);
		fd = IOS_Open("/dev/net/ncd/manage", 0);
		if (fd >= 0) {
			rc = IOS_Ioctlv(fd, 3, 0, 2, cv);
			DCInvalidateRange(cb, CFG_TOT);
			if (rc >= 0 && *(u32 *)(cb + CFG_ST) == 0) {
				u32 row = profile == 1 ? 0x8u : profile == 2 ? 0x924u : 0x1240u;
				memcpy(orig, cb, 0x1C00);
				cb[0x8] &= 0x7F; cb[0x924] &= 0x7F; cb[0x1240] &= 0x7F;
				cb[row] |= 0xA0;
				cb[0x4] = (cb[row] & 1) ? 2 : 1;                         /* wired : wireless */
				if (memcmp(orig, cb, 0x1C00) != 0) {
					DCFlushRange(cb, 0x1C00);
					rc = IOS_Ioctlv(fd, 4, 1, 1, cv);
					wr = 1;
				}
			}
			IOS_Close(fd);
		} else rc = fd;
	}
	ota_log("network profile %u selected for the update check (%s, rc %d)", (unsigned)profile, wr ? "config written" : "already set or not readable", (int)rc);
	if (cv) free(cv);
	if (cb) free(cb);
	if (orig) free(orig);
}
/* one probe run over the ladder L for dur_us (+ slack): returns 1 when the user skipped */
static int conn_loop(s32 s, struct msp_ladder *L, u32 dur_us, u32 t0)
{
	struct sockaddr_in sa, from;
	u8 buf[128];
	u32 now;
	int skipped = 0, k;
	for (;;) {
		int act;
		now = conn_us();
		if ((u32)(now - t0) >= dur_us + CONN_SLACK_US) { ota_log("conn: hard time limit"); msp_finish_now(L, now); break; }
		act = msp_poll(L, now);
		if (act == MSP_ACT_DONE) break;
		if (act == MSP_ACT_SEND) {
			u32 ip, port, n, t1, t2;
			s32 sr;
			n = msp_make_query(L, buf, now, &ip, &port);
			memset(&sa, 0, sizeof sa);
			sa.sin_family = PF_INET; sa.sin_len = 8; sa.sin_port = htons((u16)port); sa.sin_addr.s_addr = htonl(ip);
			t1 = conn_us();
			sr = net_sendto(s, buf, (s32)n, 0, (struct sockaddr *)&sa, 8);
			t2 = conn_us();
			msp_note_call(L, t2 - t1);
			if (sr < 0) msp_note_send_fail(L);
		}
		for (k = 0; k < 8; k++) {                                      /* what has arrived */
			u32 t1, t2;
			s32 rr;
			socklen_t fl = 8;
			memset(&from, 0, sizeof from); from.sin_len = 8;
			t1 = conn_us();
			rr = net_recvfrom(s, buf, (s32)sizeof buf, 0, (struct sockaddr *)&from, &fl);
			t2 = conn_us();
			msp_note_call(L, t2 - t1);
			if (rr <= 0) break;
			msp_on_reply(L, buf, (u32)rr, ntohl(from.sin_addr.s_addr), ntohs(from.sin_port), t2);
		}
		usleep(3 * 1000);
	}
	return skipped;
}
extern char ms_net_banner[56];
static void ota_conn_check(void)
{
	static const char *const vname[] = { "notrun", "running", "good", "okay", "poor", "failed" };
	static const char *const lname[] = { "none", "router", "resolver", "cloudflare", "google" };
	struct msp_result r;
	u32 hip, gw, t_start, nleg;
	s32 s, fcl;
	int skipped = 0;
	if (conn_ran) return;
	conn_ran = 1;
	if (file_exists(MSCONN_OFF)) { ota_log("conn: off (no_conn_check)"); return; }      /* the check runs BY DEFAULT (so every Wi-Fi player sees 'Wi-Fi: decent / decent. A cable is best. / unsteady. A cable is best.'; wording,: Wi-Fi is decent, a cable is best, wired is the top tier); only no_conn_check switches it off.  conn_check_on is no longer needed here or for the Wi-Fi network window */
	hip = net_gethostip();
	if (!hip) { ota_log("conn: no own address, not run"); return; }
	{
		int link, rc, adapter = MSP_NET_UNKNOWN, kind = conn_profile_kind(file_net_profile(), &link, &rc);
		int run = msp_should_run(kind, adapter, &conn_hint);
		ota_log("conn: decision: profile %u (0 = Auto), config read rc %d, active connection %s, IOS interface %s, USB LAN adapter %s (not looked for) -> %s", (unsigned)(ncfg ? (ncfg->NetworkProfile & 3) : 0), rc,
		        kind == MSP_NET_WIRED ? "wired" : kind == MSP_NET_WIRELESS ? "wireless" : "unknown", link == MSP_NET_WIRED ? "wired" : link == MSP_NET_WIRELESS ? "wireless" : "unknown", "unknown", run ? "run" : "skipped: wired");
		if (!run) return;
	}
	gw = (hip & 0xFFFFFF00u) | 1u;
	s = net_socket(PF_INET, SOCK_DGRAM, 0);                            /* protocol 0, see the DNS code above */
	if (s < 0) { ota_log("conn: socket failed (%d), not run", (int)s); return; }
	fcl = net_fcntl(s, F_GETFL, 0);
	if (fcl < 0 || net_fcntl(s, F_SETFL, fcl | 4) < 0) { net_close(s); ota_log("conn: socket not non-blocking, not run"); return; }
	{ const char *l[1] = { "Checking your connection..." }; conn_screen(l, 1); }
	t_start = conn_us();
	msp_init(&g_probe, t_start, t_start ^ (hip * 2654435761u), CONN_DURATION_US, 0);
	nleg = msp_default_legs(&g_probe, hip, gw, 0);
	ota_log("conn: start, own %u.%u.%u.%u, gateway guess %u.%u.%u.%u, %lu legs, %lu s", IPQ(hip), IPQ(gw), (unsigned long)nleg, (unsigned long)(CONN_DURATION_US / 1000000u));
	skipped = conn_loop(s, &g_probe, CONN_DURATION_US, t_start);
	net_close(s);
	if (skipped) { ota_log("conn: skipped by the user at +%lu ms", (unsigned long)((conn_us() - t_start) / 1000u)); return; }
	msp_result(&g_probe, &r);
	{
		char line[300];
		int n = snprintf(line, sizeof line, "leg=%s verdict=%s loss=%lu.%02lu%% p50=%luus p95=%luus p99=%luus jitter=%luus gap100=%lu gap250=%lu slow_calls=%lu noisy=%d sent=%lu recv=%lu router_silent=%d call_max=%luus send_fail=%lu run_ms=%lu",
		                 lname[r.leg <= 4 ? r.leg : 0], vname[r.verdict <= 5 ? r.verdict : 0], (unsigned long)(r.loss_x100 / 100u), (unsigned long)(r.loss_x100 % 100u), (unsigned long)r.p50, (unsigned long)r.p95, (unsigned long)r.p99, (unsigned long)r.jitter,
		                 (unsigned long)r.gap100, (unsigned long)r.gap250, (unsigned long)r.slow_calls, (int)r.noisy, (unsigned long)r.sent, (unsigned long)r.recv, (int)r.router_silent, (unsigned long)r.call_max_us, (unsigned long)r.send_fail, (unsigned long)r.run_ms);
		ota_log("conn: %s", line);
		if (n > 0 && n < (int)sizeof line) { line[n] = '\n'; f_mkdir_char(MSOTA_DIR); write_file(MSCONN_TXT, (const u8 *)line, (u32)n + 1u); }
	}
	{                                                                      /* the other legs, 2 s each, so the report shows the whole path: the ladder only moves outward when the router is bad */
		static const u32 xleg[2] = { MSP_LEG_CF, MSP_LEG_GOOGLE };
		static const u32 xip[2] = { 0x01010101u, 0x08080808u };
		int xi;
		for (xi = 0; xi < 2 && !skipped; xi++) {
			struct msp_result xr;
			char xl[160];
			int xn;
			s32 xs = net_socket(PF_INET, SOCK_DGRAM, 0), xf;
			if (xs < 0) break;
			xf = net_fcntl(xs, F_GETFL, 0);
			if (xf < 0 || net_fcntl(xs, F_SETFL, xf | 4) < 0) { net_close(xs); break; }
			t_start = conn_us();
			msp_init(&g_probe, t_start, t_start ^ (hip * 2654435761u) ^ (u32)xi, 2000000u, 0);
			if (!msp_add_leg(&g_probe, xleg[xi], xip[xi])) { net_close(xs); continue; }
			skipped = conn_loop(xs, &g_probe, 2000000u, t_start);
			net_close(xs);
			msp_result(&g_probe, &xr);
			xn = snprintf(xl, sizeof xl, "leg=%s verdict=%s loss=%lu.%02lu%% p50=%luus p95=%luus sent=%lu recv=%lu", lname[xr.leg <= 4 ? xr.leg : 0], vname[xr.verdict <= 5 ? xr.verdict : 0], (unsigned long)(xr.loss_x100 / 100u), (unsigned long)(xr.loss_x100 % 100u), (unsigned long)xr.p50, (unsigned long)xr.p95, (unsigned long)xr.sent, (unsigned long)xr.recv);
			ota_log("conn: %s", xl);
			if (xn > 0 && xn < (int)sizeof xl - 1) { u8 *old = NULL; u32 ol = 0; if (read_file(MSCONN_TXT, &old, &ol, 4096) == 0 && old) { char *both = (char *)malloc(ol + (u32)xn + 2u); if (both) { memcpy(both, old, ol); memcpy(both + ol, xl, (u32)xn); both[ol + (u32)xn] = '\n'; write_file(MSCONN_TXT, (const u8 *)both, ol + (u32)xn + 1u); free(both); } free(old); } }
		}
	}
	{
		const char *l[6];
		int n = 0, ms = 2000;
		if (r.verdict == MSP_V_GOOD) { l[n++] = "Your Wi-Fi is decent."; ms = 4000; }
		else if (r.verdict == MSP_V_OKAY) { l[n++] = "Your Wi-Fi is decent."; l[n++] = "A cable is best for online play."; ms = 6000; }
		else if (r.verdict == MSP_V_POOR) { l[n++] = "Your Wi-Fi is unsteady right now."; l[n++] = "Move closer or use a cable for online play."; ms = 7000; }
		else { l[n++] = "Could not check your connection.";            /* no claim about the router: its address is a guess (the network's .1), the log has router_silent */ }
		snprintf(ms_net_banner, sizeof ms_net_banner, "%s", r.verdict == MSP_V_GOOD ? "Wi-Fi: decent" : r.verdict == MSP_V_OKAY ? "Wi-Fi: decent. A cable is best." : r.verdict == MSP_V_POOR ? "Wi-Fi: unsteady. A cable is best." : "Network: not checked");
		if (conn_hint) { l[n++] = "A LAN adapter is plugged in but your"; l[n++] = "network profile uses Wi-Fi."; l[n++] = "Choose a wired profile in Wii settings."; ms += 1500; }
		conn_screen(l, n);
		usleep((useconds_t)ms * 1000);
	}
}

/* the check at every start (SD is mounted): one status line, never more than the stated limits.  Returns 1 when a newer kernel was installed (the caller then decides with the new file). */
static int precheck_done, precheck_netfail;
static int ota_early;                          /* ms_ota_precheck is running: before the IOS58 reload */
static u32 inst_shell_seq;                     /* a shell was installed by this run's boot check */
static void ota_boot_check_body(struct msota_state *kst);
static void card_boot_fetch(void);             /* the newest card container, when a virtual card exists (after the card section below) */
static void card_boot_apply(void);             /* MultishineCode / MultishineOvl of the virtual card from the downloaded container (offline: nothing to fetch) */
static void ota_boot_check(struct msota_state *kst)
{
	g_boot_ctx = 1;
	ota_boot_check_body(kst);
	card_boot_apply();                                                   /* a container that is already on the SD (fetched now, or by an earlier start whose card update was cut) */
	g_boot_ctx = 0;
}
static void ota_boot_check_body(struct msota_state *kst)
{
	u32 t0 = now_ms(), size = 0, got = 0, shl_have;
	time_t tnow = time(NULL);
	long lat;
	int r, did = 0, nr;
	char msg[80];
	if (tnow > 0 && chk_next() > (u32)tnow) { ota_log("back-off active until %lu (now %ld), boot check skipped, nothing shown", (unsigned long)chk_next(), (long)tnow); return; }     /* a recent check failed: quiet until the back-off is over */
	ota_log("boot check: now %ld, kernel floor %lu", (long)tnow, (unsigned long)kst->floor);
	ShowMessageScreen("Checking for updates...");
	conn_apply_profile(file_net_profile());                                 /* before the first network init */
	if (ota_early) {                                                       /* a Wi-Fi association before the IOS58 reload never completed in any test (21 s, then status -24); after the reload it takes 3-5 s: do not wait here at all */
		int lk0 = 0, rc00 = 0, kd0 = conn_profile_kind(file_net_profile(), &lk0, &rc00);
		if (kd0 != MSP_NET_WIRED) { early_net_timeout = 1; precheck_netfail = 2; ota_log("boot check: connection is %s, the network is tried after the IOS58 reload only", kd0 == MSP_NET_WIRELESS ? "wireless" : "of unknown kind"); return; }
	}
	{                                                                      /* Wi-Fi associates slower than a cable: give it 30 s (a known cable keeps 12 s).  for EVERY player (it was behind conn_check_on, the configuration tested all day on our Wii) */
		int lk = 0, rc0 = 0, kd = conn_profile_kind(file_net_profile(), &lk, &rc0);
		if (kd != MSP_NET_WIRED) g_boot_ms = 30000;                       /* wireless OR unknown (the 126 test: the kind was not known this early and the window stayed 12 s): only a known cable keeps 12 s; a network that is up returns at once anyway */
		ota_log("boot check: connection kind %s (config read rc %d, row %u), network window %lu ms", kd == MSP_NET_WIRED ? "wired" : kd == MSP_NET_WIRELESS ? "wireless" : "unknown", rc0, (unsigned)file_net_profile(), (unsigned long)g_boot_ms);
	}
	if (!ota_early && early_net_timeout) { g_net_wait_user = 1; g_boot_ms = 14000; ota_log("boot check: the early window got no network: second try after the IOS58 reload, window %lu ms", (unsigned long)g_boot_ms); }
	nr = ota_net_up(g_boot_ms, 1);                                         /* up to g_boot_ms from the init start (a Wii needs 4+ s the first time) */
	if (nr != 0) {
		precheck_netfail = ((nr == -2 || nr == -3) && ota_early) ? 2 : 1;   /* also a TIMEOUT in the early window (the network must be rock solid, updates depend on it): the whole check is repeated once after the IOS58 reload, with a clean IOS; a skip by the user (-4) is never repeated */
		if (nr == -3 && ota_early) early_net_timeout = 1;                /* 2: a HARD network error before the IOS58 reload (a vWii answered status -24 after 1.4 s,: the Homebrew Channel leaves IOS state behind): no back-off, the check is made again after the reload with a clean IOS */
		ota_net_down();
		if (precheck_netfail == 2) { ota_log("early network error: no back-off, the update check is repeated after the IOS58 reload"); return; }
		if (tnow > 0) chk_set(msota_backoff(nr == -4 ? MSOTA_BO_SKIPPED : MSOTA_BO_NET_FAIL, (u32)tnow, chk_next()));        /* not up in time: 10 minutes; a skip by the user: nothing */
		return;
	}
	net_t0 = now_ms(); g_boot_ms = 30000; g_net_wait_user = 0; g_conn_t0 = 0;             /* the network is up: the update questions get their own 12 s window from here (a long wait for the network must not use it up) */
	lat = ota_latest(&KIND_KRN, kst->floor, 3000, &size);
	if (lat < 0) {                                                       /* the server did not answer in time: back off */
		ota_log("boot check: the update server did not answer: the connection check still runs (it does not use the server)");
		ota_conn_check();                                                /* the connection check never depends on our server: any early way out of the update steps comes here first */
		ota_net_down();
		if (tnow > 0) chk_set(msota_backoff(MSOTA_BO_SERVER_FAIL, (u32)tnow, chk_next()));       /* the network is up, the server is silent: 1 hour */
		return;
	}
	if (lat > 0) {
		snprintf(msg, sizeof msg, "Downloading update... (any button: skip)");
		ShowMessageScreen(msg);
		r = ota_install(&KIND_KRN, (u32)lat, kst->floor ? kst->floor : 1, 12000, skip_pressed, &got);
		if (r == OU_INSTALLED) {
			kst->pending = 0; kst->fail = 0; kst->active = 0; if (kst->bad == got) kst->bad = 0;
			save_state(kst);
			snprintf(msg, sizeof msg, "Updated");
			ShowMessageScreen(msg);
			usleep(1200 * 1000);
			did = 1;
		}
	}
	shl_have = shell_have();
	if ((u32)(now_ms() - t0) >= 20000u) {                                /* too late to look for a shell: that is NOT "up to date" (Zell: the screen said so and the shell was old) */
		ota_log("boot check: %lu ms used, the shell check was not made", (unsigned long)(now_ms() - t0));
		ota_conn_check();
		ota_net_down();
		ShowMessageScreen("Could not check for updates"); usleep(900 * 1000);
		if (tnow > 0) chk_set(msota_backoff(MSOTA_BO_NET_FAIL, (u32)tnow, chk_next()));             /* ten minutes, then the next start looks again */
		return;
	} else {
		lat = ota_latest(&KIND_SHL, shl_have, 5000, &size);              /* 5 s (was 2 s: a slow answer on a home LAN counted as no news) */
		if (lat < 0) {                                                   /* no answer: the same as the kernel's: not "up to date", ask again soon */
			ota_log("boot check: the shell question got no answer: the connection check still runs");
			ota_conn_check();
			ota_net_down();
			ShowMessageScreen("Could not check for updates"); usleep(900 * 1000);
			if (tnow > 0) chk_set(msota_backoff(MSOTA_BO_NET_FAIL, (u32)tnow, chk_next()));
			return;
		}
		if (lat > 0) {
			snprintf(msg, sizeof msg, "Downloading update... (any button: skip)");
			ShowMessageScreen(msg);
			r = ota_install(&KIND_SHL, (u32)lat, shl_have ? shl_have : 1, 30000, skip_pressed, &got);
			if (r == OU_INSTALLED) {
				inst_shell_seq = got;
				did = 1;                                                    /* the restart into it (or the plain words when it is refused) comes from ota_chain_after_check, early or late */
			}
		}
	}
	if ((u32)(now_ms() - t0) < 25000u) card_boot_fetch();                /* the card files of a virtual card: only fetched here, applied after the network is down (card_boot_apply) */
	if (!inst_shell_seq) ota_conn_check();                              /* the connection check (a restart into a new shell follows an installed shell: next start then) */
	ota_net_down();                                                      /* the vBBA of the kernel owns the network from here */
	if (!did) { ShowMessageScreen("Up to date"); usleep(400 * 1000); }
	ota_log("boot check done: installed %d", did);
	chk_set(msota_backoff(did ? MSOTA_BO_INSTALLED : MSOTA_BO_SUCCESS, (u32)(tnow > 0 ? tnow : 0), chk_next()));      /* the server answered (and maybe a file was installed): no back-off */
}


static int rs_exists(void *c, const char *p)
{
	DIR d;
	(void)c;
	if (file_exists(p)) return 1;
	if (f_opendir_char(&d, p) == FR_OK) { f_closedir(&d); return 1; }
	return 0;
}
static int rs_rename(void *c, const char *a, const char *b) { (void)c; return rename_path(a, b); }
/* a file, or a folder with everything in it (the walk re-opens the folder after each delete and is bounded) */
static int rs_remove_rec(const char *p, int depth)
{
	int guard;
	for (guard = 0; guard < 400 && depth < 4; guard++) {
		DIR d;
		FILINFO fi;
		char child[64];
		int found = 0;
		if (f_opendir_char(&d, p) != FR_OK) break;                  /* a plain file (or nothing there) */
		for (;;) {
			const char *s;
			if (f_readdir(&d, &fi) != FR_OK || fi.fname[0] == 0) break;
			s = wchar_to_char(fi.fname);
			if (!strcmp(s, ".") || !strcmp(s, "..") || strlen(p) + 1 + strlen(s) >= sizeof child) continue;
			snprintf(child, sizeof child, "%s/%s", p, s);
			found = 1;
			break;
		}
		f_closedir(&d);
		if (!found) break;
		if (rs_remove_rec(child, depth + 1) != 0 && file_exists(child)) return -2;     /* an entry that cannot be deleted: the folder cannot either */
	}
	return unlink_path(p);
}
static int rs_remove(void *c, const char *p) { (void)c; return rs_remove_rec(p, 0); }
static int rs_mkdir(void *c, const char *p) { (void)c; return (int)f_mkdir_char(p); }
static void rs_log(void *c, const char *name, int how, int rc)
{
	(void)c;
	ota_log("reset: %s %s", name, how == MSR_H_MOVED ? "moved to reset_backup" : how == MSR_H_DELETED ? "deleted (the move failed)" : "FAILED (move and delete)");
	if (rc) ota_log("reset: %s: rename code %d", name, rc);
}
/* the session's own copy of the settings back to the defaults the loader uses when it finds no nincfg.bin (the memset block in main.c, see stage_loader.py), then the forced values; the device the player is on and the game location stay */
extern void ms_vcard_refresh(void); extern void ms_cfg_apply(void);
static void rs_ram_defaults(void)
{
	u32 usb;
	if (!ncfg) return;
	usb = ncfg->Config & NIN_CFG_USB;
	{
		const u32 magic = ncfg->Magicbytes, ver = ncfg->Version, gid = ncfg->GameID;
		char gp[sizeof ncfg->GamePath];
		memcpy(gp, ncfg->GamePath, sizeof gp);
		memset(ncfg, 0, sizeof(NIN_CFG));
		ncfg->Magicbytes = magic; ncfg->Version = ver; ncfg->GameID = gid;
		memcpy(ncfg->GamePath, gp, sizeof gp);
	}
	ncfg->Language = NIN_LAN_AUTO;
	ncfg->MaxPads = NIN_CFG_MAXPAD;
	ncfg->MemCardBlocks = 0x2;
	ncfg->Config = NIN_CFG_MEMCARDEMU | NIN_CFG_BBA_EMU | usb;       /* autoboot off, the rest as a fresh config */
	ncfg->VideoMode |= NIN_VID_PROG;
	ms_vcard_refresh();
	ms_cfg_apply();                                                    /* the forced rules (BBA, log, unlock read speed, ...) */
}

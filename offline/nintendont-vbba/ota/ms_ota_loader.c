static unsigned char g_mac[6];
static int g_mac_ok, g_devid_ok;
static u32 g_devid;
static char g_cid[17];                                /* the console id once known ("" before: the MAC needs the network) */

/* console id = first 8 bytes of SHA-256("ms-diag1" + MAC + Wii device id): never the raw numbers.  The MAC is only readable with the network up. */
static void diag_console(void)
{
	u8 m[8];
	int k, nz = 0;
	if (!g_mac_ok && net_started && net_get_mac_address(m) >= 0) { for (k = 0; k < 6; k++) nz |= m[k]; if (nz) { memcpy(g_mac, m, 6); g_mac_ok = 1; } }
	if (!g_devid_ok) { u32 id = 0; if (ES_GetDeviceID(&id) >= 0) { g_devid = id; g_devid_ok = 1; } }
	if (g_mac_ok || g_devid_ok) msd_console_id(g_cid, g_mac, g_devid);
}

static int diag_muted(void) { return file_exists(MSOTA_DIAG_NO); }

static void diag_fill(struct msd_info *in, const char *reason)
{
	struct msota_state st, sh;
	volatile u32 *si = SI_REGS;
	int i;
	msota_state_init(&st); msota_state_init(&sh);
	if (devices[DEV_SD]) {
		u8 *b = NULL;
		u32 n = 0;
		load_state(&st);
		if (read_file(MSOTA_SHL_ST, &b, &n, 4096) == 0) { msota_state_parse(&sh, b, n); free(b); }
	}
	memset(in, 0, sizeof *in);
	in->shell_seq = (unsigned)MS_SHELL_SEQ; in->kernel_floor = (unsigned)st.floor; in->kernel_active = (unsigned)st.active; in->stub_floor = (unsigned)sh.floor; in->stub_active = (unsigned)sh.active;
	in->abi_kernel = MSOTA_ABI; in->abi_shell = MSOTA_SHELL_ABI; in->abi_stub = MSOTA_STUB_ABI;
	in->dev = UseSD ? "SD" : "USB"; in->sd_mounted = devices[DEV_SD] ? 1 : 0; in->log_fail = g_log_fail; in->uptime_ms = (unsigned long)now_ms();
	in->reason = reason;
	PAD_ScanPads();                                                  /* ONE read per frame: the buttons come from PAD_ButtonsHeld, the port status from libogc's own bits (ms_pad_err) */
	for (i = 0; i < 4; i++) { in->pad[i].si = ms_pad_si(i); in->pad[i].err = ms_pad_err(i); in->pad[i].btn = (unsigned)PAD_ButtonsHeld(i); }
	ms_sm_read(&in->sm);
	in->pad_valid = 1;
	in->si_poll = si[12]; in->si_comcsr = si[13]; in->si_sisr = si[14]; in->si_exilk = si[15];
	in->last_key = g_last_key;
	in->console_id = g_cid[0] ? g_cid : "unknown";
}

static char g_diag_buf[MSD_PAYLOAD_MAX + 128];         /* the upload: the payload and its proof line (16 KB at most) */
static u32 diag_make(const char *reason, struct msd_info *in)
{
	u8 *sd = NULL;
	u32 sdn = 0, n;
	char pr[17];
	if (devices[DEV_SD] && read_file(MSOTA_LOG, &sd, &sdn, MSOTA_LOG_MAX) != 0) { sd = NULL; sdn = 0; }
	diag_fill(in, reason);
	n = msd_build(g_diag_buf, MSD_PAYLOAD_MAX + 1, in, (const char *)sd, sdn, g_ring.b, g_ring.n);
	msd_proof(pr, in->console_id, g_diag_buf, n);
	n += (u32)snprintf(g_diag_buf + n, sizeof g_diag_buf - n, "proof %s\n", pr);
	if (sd) free(sd);
	return n;
}

/* 0 = sent (and the server stored it); otherwise the reason in `why`.  Only over the pinned TLS (never plain HTTP). */
static int diag_send(const char *reason, char *why, size_t wn)
{
	struct msd_info in;
	u8 *body = NULL;
	u32 n, ip, blen = 0, status = 0;
	u16 port;
	char host[64];
	int r;
	if (MS_OTA_NTLSPIN <= 0) { snprintf(why, wn, "this build has no encrypted channel"); return -1; }
	if (ota_net_up_retry(30000) != 0) { snprintf(why, wn, "no network (code %d)", g_net_rc < 0 ? g_net_rc : g_net_st); ota_net_down(); return -2; }
	diag_console();
	n = diag_make(reason, &in);
	ota_server(&ip, &port, host, sizeof host);
	if (ota_url_used) { snprintf(why, wn, "a lab address is set: no upload"); ota_net_down(); return -3; }
	if (ota_ip_override) ip = ota_ip_override;
	ota_log("diagnostics: sending %lu bytes (reason %s, console %s) over the pinned TLS", (unsigned long)n, reason, g_cid[0] ? g_cid : "unknown");
	g_post_body = (const u8 *)g_diag_buf; g_post_len = n;
	r = ota_tls_get(ip, "/v1/update/diag/shell", 1024, 25000, &body, &blen, &status);
	g_post_body = NULL;
	if (body) free(body);
	ota_net_down();
	if (r != 0) { snprintf(why, wn, "%s", status == 429 ? "too many reports, try again later" : g_tls_why); ota_log("diagnostics: not sent (%s)", why); return -4; }
	ota_log("diagnostics: sent and stored");
	return 0;
}


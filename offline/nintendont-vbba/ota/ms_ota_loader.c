#define MSAUTOBOOT_MARK "sd:/multishine/autoboot_set"
/* A game is chosen from the start screen (Launch, or the set-up finished): the disc in the drive (GamePath "di") or the image file; and Auto Boot is turned on ONCE for a locked-in image file when the set-up is
   complete (msst_autoboot_set_now): the marker is written then, so the player's own Auto Boot choice in Settings is never forced again.  *save = the config must be written. */
static void start_commit(int dev, bool *save, const struct msst_facts *f)
{
	const int src = msst_source(g_drive, g_dev[dev].nstock);
	if (src == MSST_SRC_DRIVE) {
		const int changed = strcmp(ncfg->GamePath, "di") != 0;
		strcpy(ncfg->GamePath, "di");
		memcpy(&ncfg->GameID, "GALE", 4);
		DCFlushRange((void *)ncfg, sizeof(NIN_CFG));
		*save = changed != 0;
	} else *save = pick_game(dev, g_dev[dev].first) != 0;
	if (msst_autoboot_set_now(msst_setup_needed(f), src, file_exists(MSAUTOBOOT_MARK), ms_sel_saved)) {
		ncfg->Config |= NIN_CFG_AUTO_BOOT;
		write_file(MSAUTOBOOT_MARK, (const u8 *)"1", 1);
		*save = true;
		ota_log("autoboot: turned on once (the game is locked in, set-up complete); the marker %s keeps it the player's choice from now on", MSAUTOBOOT_MARK);
	}
	if (!f->card && f->phys && (ncfg->Config & NIN_CFG_MEMCARDEMU)) {        /* set up on the memory card in slot A: the game must use the real card (emulation off) */
		ncfg->Config &= ~NIN_CFG_MEMCARDEMU;
		DCFlushRange((void *)ncfg, sizeof(NIN_CFG));
		*save = true;
		ota_log("start: memory card emulation off (Multishine is on the memory card in slot A)");
	}
}

/* shl.ok from the start screen (msota_alive_due), once per run; written and read back, one log line.  The game start (ms_ota_select) still writes it too. */
static int g_alive_done;
static void start_alive(void)
{
	u8 *b = NULL;
	u32 n = 0;
	int w, ok;
	g_alive_done = 1;
	w = write_file(MSOTA_SHL_OK, (const u8 *)"1", 1);
	FlushDevices();
	ok = w == 0 && read_file(MSOTA_SHL_OK, &b, &n, 64) == 0 && n >= 1 && b && b[0] == '1';
	if (b) free(b);
	ota_log("shell: alive at the start screen (pads up, SD writable): shl.ok %s", ok ? "written" : "NOT written (the game start writes it again)");
}

/* the start screen of the Multishine shell.  Returns 1 when a game is chosen (ncfg->GamePath / GameID / the USB flag are set, *save = the config must be written), 0 = the loader's own device screen
   (no storage device with a games folder). */
int ms_start_screen(int (*browse)(void), bool *save)
{
	struct msst_facts f;
	int has[2], nst[2], dev, pill, action, redraw = 1;
	if (!devices[DEV_SD]) MountDevice(DEV_SD);
	if (!devices[DEV_SD] && !devices[DEV_USB]) return 0;
	soak_maybe_run("start screen");                                    /* Wi-Fi soak (SD:/multishine/soak_on): stays on its own screen until stopped */
	ShowMessageScreen("Looking for your Melee disc...");
	ms_sel_saved = 0;
	g_drive_ok = msst_drive_probe_allowed(IsWiiU(), isWiiVC, file_exists("sd:/multishine/no_drive_probe"));     /* A: Use the disc drive is offered only where the probe may run */
	g_drive = drive_probe();                                           /* the disc drive first; a stock Melee disc in it ends the search */
	if (g_drive) memset(g_dev, 0, sizeof g_dev);
	else { scan_dev(0); if (!g_dev[0].stopped) scan_dev(1); else memset(&g_dev[1], 0, sizeof g_dev[1]); }
	if (file_exists("sd:/multishine/slotb_existing")) slotb_ensure(0);   /* an existing player with a card but no slot B card: only on request until the kernel's slot B is proven on hardware (upstream calls it 'currently broken, shows as damaged'); fresh set-ups get it from the set-up */
	probe_files(&f);
	has[0] = g_dev[0].has_games; has[1] = g_dev[1].has_games;
	nst[0] = g_dev[0].nstock; nst[1] = g_dev[1].nstock;
	if (!has[0] && !has[1] && !g_drive && !msst_setup_needed(&f)) return 0;
	dev = msst_pick_dev((ncfg->Config & NIN_CFG_USB) != 0, nst);
	if (!has[dev] && has[!dev]) dev = !dev;
	pill = msst_show_pill(has);
	UseSD = !dev;
	if (dev) ncfg->Config |= NIN_CFG_USB; else ncfg->Config &= ~NIN_CFG_USB;
	for (;;) {
		int ch = 0, dec;
		action = msst_main_action(msst_setup_needed(&f), g_drive ? 1 : g_dev[dev].nstock);
		VIDEO_WaitVSync();
		FPAD_Update();
		if (Shutdown) LoaderShutdown();
		{ const int h = ms_hold_b(); if (h == 2) ShowMessageScreenAndExit("Returning to loader...", 0); if (h) redraw = 1; }
		if (redraw) { start_draw(action, dev, pill, &f); redraw = 0; }
		if (msota_alive_due(pads_up, devices[DEV_SD] != 0, 1, g_alive_done)) start_alive();   /* the start screen is up with the pads read: this shell works (shl.ok) */
		{
			const int key = FPAD_OK(0) ? MSST_KEY_A : FPAD_X(0) ? MSST_KEY_X : FPAD_Y(0) ? MSST_KEY_Y : FPAD_Start(0) ? MSST_KEY_START : 0;
			dec = key ? msst_key_decision(key, action, g_drive, g_dev[dev].nstock, msst_setup_needed(&f), g_drive_ok) : MSST_D_NONE;
		}
		if (dec == MSST_D_DRIVE) {
			use_drive_flow();                                          /* g_drive is set when a stock disc was found: the start screen then shows it (A: Launch, or the set-up) */
			redraw = 1;
		} else if (dec == MSST_D_BROWSER) {
			const int r = file_browser(dev, save);
			if (r >= 0) {                                              /* a stock image was locked in: it is the game; its device is the shown one */
				dev = r; UseSD = !dev;
				if (dev) ncfg->Config |= NIN_CFG_USB; else ncfg->Config &= ~NIN_CFG_USB;
				nst[0] = g_dev[0].nstock; nst[1] = g_dev[1].nstock; has[0] = g_dev[0].has_games; has[1] = g_dev[1].has_games; pill = msst_show_pill(has);
			}
			redraw = 1;
		} else if (dec == MSST_D_SETUP || dec == MSST_D_LAUNCH) {
			if (action == MSST_A_SETUP) {
				const int go = ms_setup();
				scan_dev(0); if (!g_dev[0].stopped) scan_dev(1); else memset(&g_dev[1], 0, sizeof g_dev[1]);
				nst[0] = g_dev[0].nstock; nst[1] = g_dev[1].nstock; has[0] = g_dev[0].has_games; has[1] = g_dev[1].has_games; pill = msst_show_pill(has);
				probe_files(&f);
				if (go && !msst_setup_needed(&f) && g_dev[dev].nstock <= 0 && g_dev[!dev].nstock > 0) { dev = !dev; UseSD = !dev; if (dev) ncfg->Config |= NIN_CFG_USB; else ncfg->Config &= ~NIN_CFG_USB; }
				if (go && !msst_setup_needed(&f) && (g_drive || g_dev[dev].nstock > 0)) { start_commit(dev, save, &f); return 1; }
				redraw = 1;
			} else if (action == MSST_A_LAUNCH) {
				start_commit(dev, save, &f);
				ota_log("start: launch %s", ncfg->GamePath);
				return 1;
			}
			ch = 1;
		} else if (dec == MSST_D_LIST) {
			int r;
			ms_sel_mode = 0;
			r = browse();
			if (r & 2) *save = true;
			if (r & 1) return 1;
			ch = redraw = 1;
		} else if (dec == MSST_D_SETTINGS) {
			ms_sel_mode = 1; ms_sel_saved = 0;
			browse();
			ms_sel_mode = 0;
			if (ms_sel_saved) *save = true;
			ch = redraw = 1;
		} else if (dec == MSST_D_ABOUT) {
			ms_about();
			probe_files(&f);
			ch = redraw = 1;
		} else if (pill && (FPAD_Left(0) || FPAD_Right(0) || FPAD_Up(0) || FPAD_Down(0))) {
			dev = !dev;
			UseSD = !dev;
			if (dev) ncfg->Config |= NIN_CFG_USB; else ncfg->Config &= ~NIN_CFG_USB;
			ch = redraw = 1;
		}
		(void)ch;
	}
}

/* ---- autoboot (the player's Auto Boot setting) ---- */
static int g_ab_dirty, g_ab_off;
int ms_autoboot_off(void) { return g_ab_off; }
int ms_autoboot_setup_needed(void)                      /* main: before the 'B: Cancel Autoboot' window.  1 = no Multishine files yet: no autoboot, the start screen offers the set-up */
{
	struct msst_facts f;
	probe_files(&f);
	if (msst_autoboot_allowed(msst_setup_needed(&f))) return 0;
	g_ab_off = 1;
	ota_log("autoboot: no Multishine files yet, autoboot is off for this start (set-up is offered)");
	return 1;
}
void ms_autoboot_fix(void)                              /* main: UseSD is set.  The saved GamePath missing or not stock: the stock image found takes its place */
{
	const int usb = (ncfg->Config & NIN_CFG_USB) != 0;
	char saved[300];
	int ok;
	if (file_exists("sd:/multishine/slotb_existing")) slotb_ensure(0);  /* the autoboot path never shows the start screen: same rule */
	if (file_exists(MSPHYS_MARK) && !file_exists(MSCARD_RAW) && (ncfg->Config & NIN_CFG_MEMCARDEMU)) {   /* set up on the memory card in slot A: emulation off, as start_commit */
		ncfg->Config &= ~NIN_CFG_MEMCARDEMU;
		DCFlushRange((void *)ncfg, sizeof(NIN_CFG));
		g_ab_dirty = 1;
		ota_log("autoboot: memory card emulation off (Multishine is on the memory card in slot A)");
	}
	if (ncfg->GamePath[0] == 'd' && ncfg->GamePath[1] == 'i' && (ncfg->GamePath[2] == 0 || ncfg->GamePath[2] == ':')) return;       /* the disc drive */
	snprintf(saved, sizeof saved, "%s:%s", usb ? "usb" : "sd", ncfg->GamePath);
	ok = gd_check(0, saved, 1) == 1 || gd_check(0, saved, 0) == 1;
	if (ok) return;
	scan_dev(usb); scan_dev(!usb);
	if (msst_autoboot_path(0, g_dev[usb].nstock + g_dev[!usb].nstock) < 0) { ota_log("autoboot: %s is not stock and no stock Melee v1.02 was found: the disc lock explains", saved); return; }
	{
		const int d = g_dev[usb].nstock > 0 ? usb : !usb;
		g_ab_dirty |= pick_game(d, g_dev[d].first) != 0;
		ota_log("autoboot: saved game %s is not stock or missing: using %s", saved, g_dev[d].first);
	}
}
int ms_autoboot_saved(void) { return g_ab_dirty; }


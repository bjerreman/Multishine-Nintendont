/* Multishine: the Nintendont OTA in the loader.
 *   ms_ota_select      called by main BEFORE the kernel is injected: mounts the SD card, verifies SD:/multishine/kernel.bin with the pinned release keys, applies the rollback
 *                        rules (SD:/multishine/ota.st) and returns the kernel ZIP to run, or NULL = the kernel embedded in this boot.dol (the shell's own fallback).
 *   (UpdateNintendont, the old Update key, is gone: the About page's A: Check for updates runs do_update.)  The stock updater pointed at github.com/FIX94/Nintendont and must never run in this build.  do_update asks OUR server
 *                        (plain HTTP, port 80: this console's SSL cannot talk to a modern server; every byte that matters is Ed25519-verified here) for a newer signed kernel container,
 *                        downloads it, checks it, writes kernel.new, checks it AGAIN from the SD card, then swaps it in (kernel.bin -> kernel.bak, kernel.new -> kernel.bin).
 * Never leaves the SD without a working boot: boot.dol itself is never written.
 * The loader is now the SHELL of a three-layer chain (stub -> shell -> kernel): at every start it also does a SHORT, bounded update check against our server
 * (plain HTTP to the baked server address, no DNS, hard time limits everywhere, backed off for an hour after a failure) and installs a newer signed kernel (kernel.bin) or shell (shell.dol,
 * which the stub chain-loads) exactly the way the Update key does.  The network is torn down again before the kernel starts: the vBBA owns it afterwards. */

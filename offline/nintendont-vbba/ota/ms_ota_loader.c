/* ---- SD:/multishine/ota.log: one line per step of every start and every manual check  -------------------------------------------------- */
#define MSOTA_LOG "sd:/multishine/ota.log"
#define MSOTA_LOG_MAX 16384u
extern FATFS *devices[2];
static int g_net_rc, g_net_st, g_get_rc, g_chk_err, g_contact;     /* g_contact: the server answered an update request in this run */        /* the numbers the screens show next to a failure */
static u32 g_get_status;
static char prelog[1024];
static u32 prelog_n;
static void ota_log(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
static void ota_log(const char *fmt, ...)
{
	char line[400];
	if (in_log) return;
	u8 *old = NULL, *out;
	u32 on = 0, ln, keep = 0, skip = 0;
	va_list ap;
	va_start(ap, fmt);
	{ static u32 t0log; u32 tn = now_ms(); int pre; if (!t0log) t0log = tn; pre = snprintf(line, 12, "[%lu.%01lu] ", (unsigned long)((tn - t0log) / 1000u), (unsigned long)(((tn - t0log) % 1000u) / 100u)); vsnprintf(line + pre, sizeof line - 2 - (unsigned)pre, fmt, ap); }
	va_end(ap);
	ln = (u32)strlen(line);
	line[ln++] = '\n';
	msd_ring_add(&g_ring, line, ln);
	if (!devices[DEV_SD]) {                                         /* the SD is not mounted yet (the network is started first): keep the line in RAM, it is written with the next one */
		if (prelog_n + ln < sizeof prelog) { memcpy(prelog + prelog_n, line, ln); prelog_n += ln; }
		return;
	}
	if (prelog_n) {                                                 /* write what was kept first (recursion-free: take it out of the buffer) */
		char keep_buf[sizeof prelog];
		u32 kn = prelog_n;
		memcpy(keep_buf, prelog, kn);
		prelog_n = 0;
		{ u8 *o2 = NULL; u32 on2 = 0; if (read_file(MSOTA_LOG, &o2, &on2, MSOTA_LOG_MAX) != 0) { o2 = NULL; on2 = 0; }
		  { u8 *w = (u8 *)memalign(32, on2 + kn + 32); if (w) { if (on2) memcpy(w, o2, on2); memcpy(w + on2, keep_buf, kn); f_mkdir_char(MSOTA_DIR); in_log = 1; if (write_file(MSOTA_LOG, w, on2 + kn) != 0) g_log_fail++; in_log = 0; free(w); } }
		  if (o2) free(o2); }
	}
	if (read_file(MSOTA_LOG, &old, &on, MSOTA_LOG_MAX) != 0) { old = NULL; on = 0; }
	if (on + ln > MSOTA_LOG_MAX) {                                  /* too long: drop the oldest half, at a line start */
		skip = on + ln - MSOTA_LOG_MAX / 2;
		if (skip > on) skip = on;
		while (skip < on && old[skip - 1] != '\n') skip++;
	}
	keep = on - skip;
	out = (u8 *)memalign(32, keep + ln + 32);
	if (out) {
		if (keep) memcpy(out, old + skip, keep);
		memcpy(out + keep, line, ln);
		f_mkdir_char(MSOTA_DIR);
		in_log = 1;
		if (write_file(MSOTA_LOG, out, keep + ln) != 0) g_log_fail++;      /* a failed log write used to leave no trace at all (in_log silences w_fail): now it is counted and shown by the diagnostics */
		in_log = 0;
		free(out);
	}
	if (old) free(old);
}



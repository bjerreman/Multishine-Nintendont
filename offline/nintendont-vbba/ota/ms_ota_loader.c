/* ---- pad diagnostics, E1: LOG ONLY, no behaviour change, no resets ---------------------------------------------------------------------------------------------------------------------
   Findings of the read-only investigation: the SI registers of a Wii are at 0xCD006400 (libogc on Wii and Nintendont's PADReadGC use that mirror; the GameCube mirror 0xCC00.. is a wrong read here); PAD_ScanPads
   already reads, a PAD_Read straight after it returns PAD_ERR_TRANSFER for a working pad; SI_GetType starts SI transfers of its own.  So none of those is used any more: the SI words are read from 0xCD006400, the pad
   state from libogc's own statics (si_type, sicntrl, sipacket, cmdfixdevice, __pad_*bits) at the addresses ota/gen_padsyms.sh takes from the linked ELF, and the PI interrupt words from 0xCC003000 / 0xCC003004.
   Legend:. */
#include "ms_padsyms.h"
#define SI_REGS ((volatile u32 *)0xCD006400)
static u32 sym_u32(int i, u32 off) { u32 a = ms_padsym[i]; return a ? *(volatile u32 *)(a + off) : 0; }
void ms_sm_read(struct msd_sm *m)
{
	int i;
	memset(m, 0, sizeof *m);
	m->pi_intsr = *(volatile u32 *)0xCC003000; m->pi_intmr = *(volatile u32 *)0xCC003004;
	if (!ms_padsym[0] || !ms_padsym[4]) return;
	m->sym = 1;
	m->sic_chan = (int)sym_u32(0, 0); m->sic_poll = sym_u32(0, 4);
	for (i = 0; i < 4; i++) { m->si_type[i] = sym_u32(1, (u32)i * 4); m->pkt_chan[i] = (int)sym_u32(2, (u32)i * 32); }      /* struct _sipacket is 32 bytes (chan, out, out_bytes, in, in_bytes, callback, u64 fire) */
	m->fix0 = sym_u32(3, 0);
	m->rchan = sym_u32(4, 0); m->rbits = sym_u32(5, 0); m->pend = sym_u32(6, 0); m->en = sym_u32(7, 0); m->wait = sym_u32(8, 0);
}
void ms_sm_logline(char *o, unsigned cap) { struct msd_sm m; ms_sm_read(&m); msd_sm_line(o, cap, &m); }
unsigned ms_pad_si(int port) { return port >= 0 && port < 4 ? sym_u32(1, (u32)port * 4) : 0; }                              /* the controller id libogc holds for the port (0x80 = a type transfer in flight) */
int ms_pad_err(int port)                                                                                                   /* 0 = the port is enabled for PAD_Read, -2 = still resetting / waiting, -1 = nothing there */
{
	u32 b = 0x80000000u >> (u32)port;
	if (!ms_padsym[0]) return -1;
	if (sym_u32(7, 0) & b) return 0;
	if ((sym_u32(5, 0) | sym_u32(8, 0) | sym_u32(6, 0)) & b) return -2;
	return -1;
}
static void si_regs(char *out, unsigned n)                                              /* SIPOLL / SICOMCSR / SISR / SIEXILK for the log */
{
	volatile u32 *si = SI_REGS;
	snprintf(out, n, "SIPOLL %08X SICOMCSR %08X SISR %08X SIEXILK %08X", (unsigned)si[12], (unsigned)si[13], (unsigned)si[14], (unsigned)si[15]);
}

void ms_ota_pads_ready(void)
{
	/* Called by main right after FPAD_Init.  Log only (no reset): one line every 30 frames for the first 3 s (4 VSyncs of a few hundred bytes, no scan, no read of the pads). */
	int f;
	pads_up = 1;
	ms_pads_confirm_and_chain();
	for (f = 0; f <= 180; f++) {
		if (f % 30 == 0) {
			struct msd_sm m;
			char r[120], l[256];
			ms_sm_read(&m); msd_sm_line(l, sizeof l, &m); si_regs(r, sizeof r);
			ota_log("%s | f%d | %s", l, f, r);
		}
		if (f < 180) VIDEO_WaitVSync();
	}
}

/* AUTOBOOT only (stage_loader.py, main.c, after the "B: Cancel Autoboot" loop): the game must not start before a GameCube controller answered.  The Nintendont kernel cannot connect a Wavebird after
   the game started ("if wavebird disconnects it cant reconnect", PADReadGC).  Field logs: after an unattended auto-update restart with autoboot the Wavebird receiver reported
   type A8000000 (receiver present, SI_WIRELESS_RECEIVED clear = no controller linked: the Wavebird had switched itself off) for 8 s, nobody answered, the game started and the pad was dead in game; after a
   restart with a button pressed it answered EB50EE00 within 3 s.  So: wait for any GameCube pad (the pad scan mask); a connected Wii remote ends the wait at 1 s, none answered after 8 s (a Wavebird that is switched on together with the Wii needs several seconds to link,: no notice for that): say so on the
   screen and keep waiting up to 15 s in all for the player to switch the pad on; B on a Wii remote skips the wait.  (A receiver check through libogc's SI type call or its cached type does not work reliably: the call answers 'busy' for an unpolled port,
   the symbol read of si_type was garbage in some builds.)  Nothing plugged in: 20 s once per autoboot.  The outcome goes to ota.log. */
static void wb_notice(void)
{
	const char *a = "No GameCube controller found", *b = "Press a button to wake it";
	ClearScreen();
	PrintFormat(DEFAULT_SIZE, BLACK, (640 - (int)GRRLIB_WidthTTF(myFont, a, DEFAULT_SIZE)) / 2, MENU_POS_Y + 20 * 11, "%s", a);
	PrintFormat(DEFAULT_SIZE, BLACK, (640 - (int)GRRLIB_WidthTTF(myFont, b, DEFAULT_SIZE)) / 2, MENU_POS_Y + 20 * 12, "%s", b);
	UpdateScreen();
	ClearScreen();
}

void ms_ota_pad_settle(void)
{
	int f, said = 0, skipped = 0, wm = 0;
	u32 mask = 0;
	if (!pads_up) return;
	if (IsWiiU()) { ota_log("pad settle (autoboot): skipped on a Wii U (no GameCube ports; the USB adapter is read by the kernel)"); return; }
	for (f = 0; f < 900; f++) {
		VIDEO_WaitVSync();
		mask = PAD_ScanPads();
		if (mask) break;
		if (f == 60) { u32 t = 0; WPAD_ScanPads(); if (WPAD_Probe(0, &t) == WPAD_ERR_NONE) { wm = 1; break; } }      /* a Wii remote is already connected: its player does not wait */
		if (f >= 480 && !said) { said = 1; wb_notice(); }
		if (f >= 480) { WPAD_ScanPads(); if (WPAD_ButtonsDown(0) & WPAD_BUTTON_B) { skipped = 1; break; } }
	}
	ota_log("pad settle (autoboot): %s after %d frames, connected mask %lX%s", mask ? "pad answered" : "no GameCube pad answered", f, (unsigned long)mask, wm ? " (a Wii remote is connected: no wait)" : skipped ? " (skipped with B)" : said ? " (notice shown)" : "");
}

static int skip_pressed(void)
{
	if (pads_up) { FPAD_Update(); return (FPAD_Cancel(0) || FPAD_OK(0) || FPAD_Start(0)) ? 1 : 0; }      /* any of B, A, Start skips the network step (the network waits must not feel like a timer you have to sit through) */
	PAD_ScanPads();
	return (PAD_ButtonsHeld(0) & (PAD_BUTTON_B | PAD_BUTTON_A | PAD_BUTTON_START)) ? 1 : 0;
}

/* start the libogc network (a thread; returns at once).  0 = started or already running */
static u32 g_conn_t0;              /* ONE clock for the whole "Connecting..." wait: set at the first network start, kept across the early and the late check and across restarts, cleared when the network is up */
#define CONN_SKIP_AFTER_MS 30000u  /* the user cannot skip before this */
static u32 conn_elapsed(void) { return g_conn_t0 ? (u32)(now_ms() - g_conn_t0) : 0u; }
static int skip_ok(void) { return conn_elapsed() >= CONN_SKIP_AFTER_MS && skip_pressed(); }
static int ota_net_start(void)
{
	if (net_started) return 0;
	net_t0 = now_ms();
	if (!g_conn_t0) g_conn_t0 = net_t0;
	g_net_rc = (int)net_init_async(NULL, NULL);
	ota_log("net_init_async -> %d", g_net_rc);
	if (g_net_rc < 0) { g_net_st = g_net_rc; return -1; }
	net_started = 1;
	return 0;
}

/* the very first thing the shell does after the video is up: the Wii's network needs 4 s and more on the first init, so it starts now and the check finds it up (main.c calls this) */
void ms_ota_net_early(void)
{
	/* NO early start any more (ota.log 133: the init started here ran against the Wii's own connection selection, before the profile is applied, failed after 21 s, and the later net_deinit
	   before the IOS58 reload blocked for those 20 s: the boot took 20 s longer for nothing).  The check starts the network itself, after the profile is selected; a cable loses only its few seconds of head start. */
}

static void ota_net_down(void);
static int g_net_wait_user;         /* no network: wait for the USER to skip (any button), never give up by itself; set for the late boot check after an early timeout */
static int g_net_tries;            /* restarts of the network init while waiting for the user */
static void wait_line(u32 ms)
{
	char t[72];
	int w;
	(void)ms;                                                                  /* the shown time is the one clock of the whole wait, not this window's */
	if (conn_elapsed() >= CONN_SKIP_AFTER_MS) snprintf(t, sizeof t, "Connecting... %lu s. Hold any button to continue without it", (unsigned long)(conn_elapsed() / 1000u));
	else snprintf(t, sizeof t, "Connecting... %lu s", (unsigned long)(conn_elapsed() / 1000u));
	w = (int)GRRLIB_WidthTTF(myFont, t, DEFAULT_SIZE);
	ClearScreen();
	PrintFormat(DEFAULT_SIZE, BLACK, (640 - w) / 2, 232, "%s", t);
	GRRLIB_Render();
	ClearScreen();
}

/* wait for the network until budget_ms after the init was started (polling; show = one muted line with the seconds, hold B skips).  0 = up, -1 init call failed, -2 a real error status,
   -3 not up in time, -4 skipped by the user (g_net_rc / g_net_st keep the raw numbers).  An init that is still busy is left running. */
static int ota_net_up(u32 budget_ms, int show)
{
	u32 ip, shown = 0;
	s32 st, last = 0x7FFFFFF;
	if (ota_net_start() != 0) return -1;
	for (;;) {
		int again = 0;
		if (show && g_net_wait_user && skip_ok()) { ota_log("net wait skipped by the user at +%lu ms (after %d restart(s))", (unsigned long)(now_ms() - net_t0), g_net_tries); return -4; }
		st = net_get_status();
		g_net_st = (int)st;
		if (st != last) { ota_log("net_get_status %d at +%lu ms", (int)st, (unsigned long)(now_ms() - net_t0)); last = st; }
		if (st == 0) {
			ip = net_gethostip();
			ota_log("net up after %lu ms from the init start, ip %u.%u.%u.%u", (unsigned long)(now_ms() - net_t0), (unsigned)(ip >> 24), (unsigned)((ip >> 16) & 255), (unsigned)((ip >> 8) & 255), (unsigned)(ip & 255));
			return 0;
		}
		if (st < 0 && st != -EBUSY && st != -ETIMEDOUT && st != -EAGAIN) { ota_log("net error status %d", (int)st); if (!g_net_wait_user) return -2; again = 1; }   /* -EBUSY / -EAGAIN: still working */
		else if (past(net_t0, budget_ms)) { ota_log("net not up after %lu ms (last status %d)", (unsigned long)(now_ms() - net_t0), (int)st); if (!g_net_wait_user) return -3; again = 1; }
		if (again) {                                                      /* waiting for the user: a fresh network init, again and again, until it is up or the user skips */
			g_net_tries++;
			ota_log("no network yet: restarting the network init (try %d); any button continues without it", g_net_tries + 1);
			ota_net_down();
			usleep(300 * 1000);
			if (ota_net_start() != 0) usleep(2000 * 1000);
			last = 0x7FFFFFF;
			continue;
		}
		if (show) {
			if (skip_ok()) { ota_log("net wait skipped by the user at +%lu ms", (unsigned long)(now_ms() - net_t0)); return -4; }
			if ((u32)(now_ms() - shown) >= 500u && (u32)(now_ms() - net_t0) >= 500u) { shown = now_ms(); wait_line(now_ms() - net_t0); }
		}
		usleep(20 * 1000);
	}
}

static void ota_net_down(void)
{
	u32 t0;
	s32 st;
	if (!net_started) return;
	t0 = now_ms();
	st = net_get_status();
	while ((st == -EBUSY || st == -EAGAIN || st == -ETIMEDOUT) && !past(t0, 3000)) { usleep(20 * 1000); st = net_get_status(); }     /* never tear down an init that is still running if it is about to finish */
	ota_log("net_deinit (status %d, settled %lu ms)", (int)st, (unsigned long)(now_ms() - t0));
	net_deinit();
	net_started = 0;
}

/* a started init that is not needed (check skipped) or must not run on: stop it now, before the IOS58 reload */
static void ota_net_abort(void)
{
	if (!net_started) return;
	ota_log("net_deinit now (status %d, %lu ms after the init start)", (int)net_get_status(), (unsigned long)(now_ms() - net_t0));
	net_deinit();
	net_started = 0;
}

/* init, and if that fails once more from scratch (a half initialised stack from an earlier attempt, a slow association) */
static int ota_net_up_retry(u32 budget_ms)
{
	int r = ota_net_up(budget_ms, 0);
	if (r != 0) {
		ota_log("net init failed (%d): net_deinit and one fresh attempt", r);
		ota_net_down();
		r = ota_net_up(budget_ms / 2u, 0);
	}
	return r;
}

/* the server this console talks to: the baked address; SD:/multishine/ota_url.txt (lab) = "http://A.B.C.D[:port]" and an optional second line with the Host header */
static u32 ota_ip_override;        /* set by a successful DNS fallback: the rest of this run talks to that address */
static int ota_url_used;           /* SD:/multishine/ota_url.txt gave the address (lab): no DNS fallback then */
static void ota_server(u32 *ip, u16 *port, char *host, size_t hn)
{
	u8 *b = NULL;
	u32 len = 0, i;
	char tmp[160];
	{ mw2_u32 dip = 0; unsigned pp; msota_parse_ip(MSOTA_IP, &dip, &pp); *ip = dip; }
	*port = 80;
	snprintf(host, hn, "%s", MSOTA_HOSTNAME);
	if (read_file(MSOTA_URLF, &b, &len, 200) == 0) {
		i = 0;
		while (i < len && i < sizeof(tmp) - 1 && b[i] >= 32 && b[i] < 127) { tmp[i] = (char)b[i]; i++; }
		tmp[i] = 0;
		if (strncmp(tmp, "http://", 7) == 0) {
			mw2_u32 nip = 0;
			unsigned pp;
			if (msota_parse_ip(tmp + 7, &nip, &pp) == 0) {
				char *e;
				ota_url_used = 1;
				*ip = nip;
				if (pp) *port = (u16)pp;
				snprintf(host, hn, "%s", tmp + 7);
				for (e = host; *e && *e != '/'; e++) {}
				*e = 0;
			}
		}
		free(b);
	}
	if (!ota_url_used && ota_ip_override) *ip = ota_ip_override;
}

static u32 ota_server_baked_ip(void) { mw2_u32 dip = 0; unsigned pp; msota_parse_ip(MSOTA_IP, &dip, &pp); return dip; }

/* GET path from the server within deadline_ms (connect, request and the whole answer); the body goes to a new 32-byte aligned buffer.  0 = HTTP 200 with a body,
   -1 socket / connect / timeout, -2 not 200 or no Content-Length, -3 too big / memory */
/* ---- DNS first, the baked address last.  multishine.link is resolved with our own raw UDP A query (msdns_*, a non-blocking socket, 2 s per try and one
   retry; libogc's name lookup can hang without a timeout and is never used) sent to the gateway guess (the Wii's address with the last byte 1: libogc does not expose the DHCP resolver) and then
   to 1.1.1.1.  The answer is parsed defensively and a private address is refused; the request goes to the answer with Host: multishine.link.  If the lookup or the connection fails, the next
   address is tried: the last good answer kept in SD:/multishine/ota.ip (at most 30 days old, public), then the baked address.  Everything that comes from the server is signature-verified, so a wrong
   address cannot install anything.  SD:/multishine/ota_url.txt (lab) keeps working and switches all of this off.  The boot check stays inside its 12 s from the network start in all. ---- */
#define MSOTA_DNS_ON "sd:/multishine/dns_on"      /* opt-in (dev): the UDP DNS lookup; default off, the baked address is used directly */
#define MSOTA_IPF "sd:/multishine/ota.ip"
static int g_boot_ctx;             /* the boot check is running */
static int early_net_timeout;      /* the early (before the IOS58 reload) network window timed out: the late check tries once more */
static u32 g_boot_ms = 12000;      /* the boot check's network window from the init start: 12 s, 26 s when the active connection is Wi-Fi and the Connection check is on (a Wi-Fi association took about 15 s on our Wii; with 12 s the network never came up in the early check, so no update check and no connection check,) */
static u32 ota_dns_ip, ota_cache_ip;
static int ota_dns_tried, ota_ip_saved;

struct dns_sock { s32 s; u32 server; int conn; };      /* conn: the socket is connect()ed to the server, send / recv instead of sendto / recvfrom */
static s32 g_dns_serr, g_dns_rerr, g_dns_rn, g_dns_calls;
static char g_dns_hex[40];                                 /* the first received datagram: byte count and its first 16 bytes (for the log) */
                        /* the last raw send / recv results below zero (for the log: the failing call was never named before) */
static long dns_send(void *c, const mw2_u8 *p, mw2_u32 n)
{
	struct dns_sock *d = (struct dns_sock *)c;
	struct sockaddr_in sa;
	memset(&sa, 0, sizeof sa);
	sa.sin_family = PF_INET; sa.sin_len = 8; sa.sin_port = htons(53); sa.sin_addr.s_addr = htonl(d->server);       /* the IOS wants a sockaddr of exactly 8 bytes: sin_len 8 AND tolen 8 (libogc copies sa_len bytes; 16 gave -22 EINVAL on a Wii) */
	{
		s32 r = d->conn ? net_send(d->s, p, (s32)n, 0) : net_sendto(d->s, p, (s32)n, 0, (struct sockaddr *)&sa, 8);
		if (r < 0) g_dns_serr = r;
		return r;
	}
}
static void dns_note(const mw2_u8 *b, s32 n)
{
	int k, m = 0;
	if (g_dns_rn) return;
	g_dns_rn = n;
	for (k = 0; k < 16 && k < n; k++) m += snprintf(g_dns_hex + m, sizeof g_dns_hex - (size_t)m, "%02X", b[k]);
}
static long dns_recv(void *c, mw2_u8 *b, mw2_u32 cap)
{
	struct dns_sock *d = (struct dns_sock *)c;
	struct sockaddr_in from;
	socklen_t fl = 8;                                          /* the IOS fills a sockaddr of 8 bytes */
	s32 res;
	g_dns_calls++;
	if (d->conn) { res = net_recv(d->s, b, (s32)cap, 0); if (res > 0) { dns_note(b, res); return res; } }
	else { memset(&from, 0, sizeof from); from.sin_len = 8; res = net_recvfrom(d->s, b, (s32)cap, 0, (struct sockaddr *)&from, &fl);
	       if (res > 0) { dns_note(b, res); return ntohl(from.sin_addr.s_addr) == d->server ? res : 0; } }                           /* an answer from somebody else is ignored */
	if (res == 0 || res == -EAGAIN || res == -56) return 0;
	g_dns_rerr = res;
	return -1;
}
static mw2_u32 dns_now(void *c) { (void)c; return now_ms(); }
static void dns_wait(void *c, mw2_u32 ms) { (void)c; usleep(ms * 1000u); }

#define IPQ(x) (unsigned)((x) >> 24), (unsigned)(((x) >> 16) & 255), (unsigned)(((x) >> 8) & 255), (unsigned)((x) & 255)

/* 0 = ota_dns_ip is the address multishine.link resolved to */
static int ota_dns_lookup_x(u32 budget_ms, u32 per_ms, unsigned tries, int fallback);
static int ota_dns_lookup(u32 budget_ms) { return ota_dns_lookup_x(budget_ms, 2000, 2, 0); }
/* fallback: per resolver one query of per_ms (the gateway guess, 1.1.1.1, 8.8.8.8), never longer than budget_ms in all */
static int ota_dns_lookup_x(u32 budget_ms, u32 per_ms, unsigned tries, int fallback)
{
	u32 t0 = now_ms(), hip = net_gethostip(), servers[3], n = 0, i;
	mw2_u32 ip = 0;
	ota_log("dns: resolving %s (budget %lu ms)", MSOTA_HOSTNAME, (unsigned long)budget_ms);
	if (fallback) n = (u32)mssp_resolvers(hip ? (hip & 0xFFFFFF00u) | 1u : 0u, 0x01010101u, 0x08080808u, servers);
	else {
	if (hip) servers[n++] = (hip & 0xFFFFFF00u) | 1u;
	servers[n++] = 0x01010101u;
	}
	for (i = 0; i < n; i++) {
		struct dns_sock d;
		struct msdns_io io;
		int rc, lp = -1;
		u32 spent = (u32)(now_ms() - t0);
		if (spent + (fallback ? 200u : 300u) >= budget_ms) { ota_log("dns: out of time"); break; }
		int mode;
		d.server = servers[i];
		for (mode = 0; mode < 2; mode++) {                           /* 0: sendto / recvfrom, 1: a connect()ed UDP socket with send / recv (if the first fails with a socket error) */
		g_dns_serr = g_dns_rerr = g_dns_rn = g_dns_calls = 0; g_dns_hex[0] = 0; d.conn = mode;
		d.s = net_socket(PF_INET, SOCK_DGRAM, 0);                    /* protocol 0 like the TCP path: the IOS socket call answers -123 (EPROTONOSUPPORT) to IPPROTO_UDP (17), seen on a Wii */
		if (d.s < 0) { ota_log("dns: socket failed (%d)", (int)d.s); return -1; }
		{ s32 fcl = net_fcntl(d.s, F_GETFL, 0); if (fcl < 0 || net_fcntl(d.s, F_SETFL, fcl | 4) < 0) { net_close(d.s); ota_log("dns: socket not non-blocking"); return -1; } }
		if (mode == 1) {
			struct sockaddr_in sa;
			s32 cr;
			memset(&sa, 0, sizeof sa);
			sa.sin_family = PF_INET; sa.sin_len = sizeof sa; sa.sin_port = htons(53); sa.sin_addr.s_addr = htonl(d.server);
			cr = net_connect(d.s, (struct sockaddr *)&sa, sizeof sa);
			if (cr < 0 && cr != -EINPROGRESS) { net_close(d.s); ota_log("dns: connect() of the UDP socket failed (%d)", (int)cr); break; }
		}
		io.ctx = &d; io.send = dns_send; io.recv = dns_recv; io.now = dns_now; io.wait = dns_wait;
		rc = msdns_resolve(&io, (unsigned)((now_ms() ^ (servers[i] * 2654435761u)) & 0xFFFFu), MSOTA_HOSTNAME, mode ? (per_ms < 1500u ? per_ms : 1500u) : per_ms, mode ? 1 : tries, budget_ms - spent, &ip, &lp);       /* the second socket mode is a short last try: a boot check must not burn its whole budget here */
		net_close(d.s);
		ota_log("dns: server %u.%u.%u.%u (%s) -> rc %d (parse %d: %s), last send error %d, last recv error %d, recv calls %d, first datagram %d bytes %s%s", IPQ(servers[i]), mode ? "connected socket" : "sendto/recvfrom", rc, lp, lp >= 0 ? msdns_err(lp) : "no packet parsed", (int)g_dns_serr, (int)g_dns_rerr, (int)g_dns_calls, (int)g_dns_rn, g_dns_hex, rc == 0 ? "" : ", next");
		if (rc == 0) { ota_dns_ip = ip; ota_log("dns: %s is %u.%u.%u.%u after %lu ms", MSOTA_HOSTNAME, IPQ(ip), (unsigned long)(now_ms() - t0)); return 0; }
		if (rc != -2) break;                                         /* an answer, a no, a timeout: the other socket mode would not change it; only a socket error tries the second mode */
		}
	}
	ota_log("dns: no answer after %lu ms", (unsigned long)(now_ms() - t0));
	return -1;
}

static void ota_cache_load(void)
{
	u8 *b = NULL;
	u32 n = 0;
	time_t tn = time(NULL);
	char t[64];
	if (read_file(MSOTA_IPF, &b, &n, 63) != 0) return;
	memcpy(t, b, n); t[n] = 0;
	free(b);
	{ mw2_u32 ip = 0; if (msota_ipcache_parse(t, tn > 0 ? (mw2_u32)tn : 0, &ip)) { ota_cache_ip = ip; ota_log("ota.ip: %u.%u.%u.%u (a good answer of an earlier run)", IPQ(ip)); } else ota_log("ota.ip ignored (old, private or unreadable)"); }
}

static void ota_cache_save(u32 ip)
{
	char t[40];
	time_t tn = time(NULL);
	msota_ipcache_fmt(t, sizeof t, ip, tn > 0 ? (mw2_u32)tn : 0);
	f_mkdir_char(MSOTA_DIR);
	write_file(MSOTA_IPF, (const u8 *)t, (u32)strlen(t));
	ota_log("ota.ip written: %u.%u.%u.%u", IPQ(ip));
}

/* ota.ip follows the pinned key only.  WRITE after a TLS request completed at a non-baked address, CLEAR when the baked address proved itself again (ms_srvpick.h). */
#define MSOTA_NO_DNS "sd:/multishine/no_dns"       /* switches the DNS fallback off (the baked address and ota.ip only) */
static void ota_cache_after_tls(u32 ip, u32 baked)
{
	switch (mssp_after(1, ip, baked, ota_cache_ip)) {
	case MSSP_C_WRITE: ota_cache_save(ip); ota_cache_ip = ip; ota_log("ota.ip: %u.%u.%u.%u proved the pinned key", IPQ(ip)); break;
	case MSSP_C_CLEAR: unlink_path(MSOTA_IPF); ota_cache_ip = 0; ota_log("ota.ip removed: the baked address answered with the pinned key again"); break;
	}
}
static int ota_fb_done;            /* the fallback lookup ran (or was refused) in this run */
/* the baked address failed: look the name up once per run, capped at 1.5 s (the only UDP socket of the update path on a default SD: the GameCube pads were lost when the early check's
   DNS really sent and received in so this runs only when the update check is failing anyway) */
static void ota_dns_fallback(u32 left)
{
	if (ota_fb_done || ota_dns_ip || ota_url_used) return;
	ota_fb_done = 1;
	if (file_exists(MSOTA_NO_DNS)) { ota_log("dns: fallback off (no_dns)"); return; }
	if (left < 2500u) { ota_log("dns: fallback skipped, only %lu ms left", (unsigned long)left); return; }
	ota_log("dns: the baked address did not answer: fallback lookup of %s", MSOTA_HOSTNAME);
	if (ota_dns_lookup_x(1500u, 500u, 1u, 1) == 0 && ota_dns_ip == ota_server_baked_ip()) ota_log("dns: the answer is the baked address (nothing new to try)");
	else if (ota_dns_ip) ota_log("dns: answer %u.%u.%u.%u differs from the baked address: tried with the pinned key first", IPQ(ota_dns_ip));
}

/* ---- TLS first: the pinned Ed25519 TLS 1.3 client of offline/net/tls/ over a non-blocking libogc socket (ms_tlsget.c).  Port 8443 of the same host (the update server's TLS listener (not in this repository) update_handler: the read-only
   /v1/update routes).  ANY failure (connect, handshake, pin mismatch, timeout, a status other than 200) falls back to plain signed HTTP: the files stay signature-verified, TLS only adds privacy.  After a
   failure TLS is not tried again in this run.  Entropy: the shell has no hardware source; the pool mixes the tick counter, the clock, the console's device id, the jitter of 64 short sleeps, MEM2 contents
   and a one-time seed file (SD:/multishine/tls.seed, renewed after every handshake).  That is weak (the credit is a claim, not a measurement) but enough here: the server is authenticated by the pin and the
   file by its signature, so a guessed ephemeral key could at most let an eavesdropper read a public file. ---- */
#define MSOTA_TLS_PORT 8443
#define MSOTA_SEED_F "sd:/multishine/tls.seed"
static struct sdc_rng tls_rng;
static int tls_rng_seeded, ota_tls_dead;

struct tls_sock { s32 s; };
static int ts_recv(void *c, sdc_u8 *b, sdc_u32 max)
{
	s32 r = net_recv(((struct tls_sock *)c)->s, b, (s32)max, 0);
	if (r > 0) return (int)r;
	if (r == 0) return -1;                                           /* the peer closed */
	return (r == -EAGAIN || r == -56) ? 0 : -1;
}
static int ts_send(void *c, const sdc_u8 *b, sdc_u32 n)
{
	s32 r = net_write(((struct tls_sock *)c)->s, b, (s32)n);
	if (r >= 0) return (int)r;
	return (r == -EAGAIN || r == -56) ? 0 : -1;
}
static sdc_u32 ts_now(void *c) { (void)c; return now_ms(); }
static void ts_wait(void *c, sdc_u32 ms) { (void)c; usleep(ms * 1000u); }
static void *ts_alloc(void *c, sdc_u32 n) { (void)c; return memalign(32, (n + 31u) & ~31u); }
static int ts_rand(void *c, sdc_u8 *o, sdc_u32 n) { (void)c; if (!sdc_rng_ready(&tls_rng)) return 1; sdc_rng_bytes(&tls_rng, o, n); return 0; }

static void tls_seed_pool(void)
{
	u64 t = gettime();
	u32 id = 0, i, last = (u32)gettime();
	u8 *b = NULL;
	u32 n = 0;
	sdc_rng_init(&tls_rng);
	sdc_rng_mix(&tls_rng, (const sdc_u8 *)&t, sizeof t, 16);
	{ time_t tn = time(NULL); sdc_rng_mix(&tls_rng, (const sdc_u8 *)&tn, sizeof tn, 8); }
	if (ES_GetDeviceID(&id) >= 0) sdc_rng_mix(&tls_rng, (const sdc_u8 *)&id, sizeof id, 32);
	{ u32 ip = net_gethostip(); sdc_rng_mix(&tls_rng, (const sdc_u8 *)&ip, sizeof ip, 8); }
	for (i = 0; i < 64; i++) {                                        /* the jitter of short sleeps and the timer: one claimed bit each */
		u32 now;
		usleep(150 + (i & 3) * 37);
		now = (u32)gettime();
		sdc_rng_mix_u32(&tls_rng, now - last, 1);
		last = now;
	}
	{ u32 mem2 = (u32)SYS_GetArena2Hi() - 4096u; sdc_rng_mix(&tls_rng, (const sdc_u8 *)mem2, 1024, 16); }          /* whatever MEM2 holds just below the arena (not credited more) */
	if (read_file(MSOTA_SEED_F, &b, &n, 64) == 0) { sdc_rng_mix(&tls_rng, b, n, 64); free(b); }
	tls_rng_seeded = 1;
}

static void tls_seed_renew(void)                                      /* a fresh seed for the next run, from this run's pool */
{
	u8 s[32];
	sdc_rng_bytes(&tls_rng, s, sizeof s);
	f_mkdir_char(MSOTA_DIR);
	write_file(MSOTA_SEED_F, s, sizeof s);
}

/* 0 = *body / *blen / *status set (a 200); otherwise a failure reason in g_tls_why */
static char g_tls_why[64];
static u32 g_tls_conn_ms, g_tls_hs_ms;   /* soak mode: the last ota_tls_get's connect time and handshake time (ms; 0 = not reached) */
static const u8 *g_post_body;       /* diagnostics: POST this text over the same pinned TLS instead of a GET (set only by diag_send) */
static u32 g_post_len;
static int ota_tls_get(u32 ip, const char *path, u32 max, u32 deadline_ms, u8 **body, u32 *blen, u32 *status)
{
	struct sockaddr_in sa;
	struct tls_sock ts;
	struct mstls_net net;
	struct mstls_result res;
	u32 t0 = now_ms();
	s32 s, fl, r;
	int rc;
	*body = NULL; *blen = 0; *status = 0;
	if (!tls_rng_seeded) tls_seed_pool();
	s = net_socket(PF_INET, SOCK_STREAM, 0);
	if (s < 0) { snprintf(g_tls_why, sizeof g_tls_why, "socket %d", (int)s); return -1; }
	fl = net_fcntl(s, F_GETFL, 0);
	if (fl < 0 || net_fcntl(s, F_SETFL, fl | 4) < 0) { net_close(s); snprintf(g_tls_why, sizeof g_tls_why, "non-blocking failed"); return -1; }
	memset(&sa, 0, sizeof sa);
	sa.sin_family = PF_INET; sa.sin_len = sizeof sa; sa.sin_port = htons(MSOTA_TLS_PORT); sa.sin_addr.s_addr = htonl(ip);
	for (;;) {
		if (past(t0, deadline_ms)) { net_close(s); snprintf(g_tls_why, sizeof g_tls_why, "connect timeout"); return -1; }
		r = net_connect(s, (struct sockaddr *)&sa, sizeof sa);
		if (r >= 0 || r == -EISCONN) break;
		if (r == -EINPROGRESS || r == -EALREADY) { usleep(20 * 1000); continue; }
		net_close(s); snprintf(g_tls_why, sizeof g_tls_why, "connect %d", (int)r); return -1;
	}
	g_tls_conn_ms = (u32)(now_ms() - t0);
	ts.s = s;
	net.ctx = &ts; net.recv = ts_recv; net.send = ts_send; net.now = ts_now; net.wait = ts_wait; net.alloc = ts_alloc;
	if (g_post_body) rc = mstls_post(&net, MSOTA_HOSTNAME, path, (const sdc_u8 *)g_post_body, g_post_len, (const sdc_u8 *)ms_ota_tls_pins, MS_OTA_NTLSPIN, ts_rand, NULL, deadline_ms - (u32)(now_ms() - t0), &res);
	else rc = mstls_get(&net, MSOTA_HOSTNAME, path, (const sdc_u8 *)ms_ota_tls_pins, MS_OTA_NTLSPIN, ts_rand, NULL, max, deadline_ms - (u32)(now_ms() - t0), &res);
	net_close(s);
	g_tls_hs_ms = (u32)res.hs_ms;
	*status = (u32)res.status;
	if (rc != MSTLS_OK) {
		snprintf(g_tls_why, sizeof g_tls_why, "%s (tls err %d, alert %d, http %d)", mstls_err(rc), res.tls_err, res.alert, res.status);
		if (res.body) free(res.body);
		return -1;
	}
	ota_log("tls: handshake ok in %lu ms, %s: %lu bytes in %lu ms", (unsigned long)res.hs_ms, path, (unsigned long)res.clen, (unsigned long)(now_ms() - t0));
	tls_seed_renew();
	*body = res.body; *blen = res.clen;
	return 0;
}

static int ota_get_raw(const char *path, u32 max, u32 deadline_ms, u8 **body, u32 *blen, u32 *status);
static int ota_get(const char *path, u32 max, u32 deadline_ms, u8 **body, u32 *blen, u32 *status)
{
	u32 t0 = now_ms(), baked, saved = ota_ip_override, n = 0, i, k = 0;
	mssp_u32 cand[MSSP_MAX];
	const char *how[MSSP_MAX];
	u16 port;
	char host[64];
	int rc = -1;
	ota_ip_override = 0;
	ota_server(&baked, &port, host, sizeof host);                   /* the baked (or ota_url.txt) address; sets ota_url_used */
	ota_ip_override = saved;
	*body = NULL; *blen = 0; *status = 0;
	if (ota_url_used) { cand[0] = baked; how[0] = "ota_url.txt"; n = 1; }
	else {
		u32 left = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : 20000u;
		if (!ota_dns_tried) {                                        /* once per run, before the first request */
			ota_dns_tried = 1;
			ota_cache_load();
			if (!file_exists(MSOTA_DNS_ON)) { ota_log("dns: off, baked IP");          /* ..41 and 43 lost the GameCube pads whenever the UDP DNS really sent and received in the early check (42 did not): no UDP socket at all unless SD:/multishine/dns_on */
				ota_log("dns: fallback %s: a lookup only when the baked address fails", file_exists(MSOTA_NO_DNS) ? "off (no_dns)" : "on"); }
			else if (left >= 1500u) ota_dns_lookup(left / 2u > 5000u ? 5000u : left / 2u);
			else ota_log("dns: skipped, only %lu ms left of the boot budget", (unsigned long)left);
		}
		/* (ms_srvpick.h): proven in this run, baked, ota.ip, dns.  proven, dns, ota.ip, baked (with dns_on only).  The same address is never tried twice. */
		n = (u32)mssp_order(ota_ip_override, baked, ota_cache_ip, ota_dns_ip, cand, how);
		(void)k;
	}
	if (MS_OTA_NTLSPIN > 0 && !ota_url_used && !ota_tls_dead && n > 0) {          /* TLS first, to the first address; any failure falls back to plain signed HTTP */
		u32 left = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : 20000u, dl = deadline_ms, tip = 0;
		for (i = 0; i < n && !tip; i++) tip = cand[i];
		if (dl > left) dl = left;
		if (tip && dl >= 800u) {                                      /* ROCK SOLID (ota.log 135: one 2 s TLS try and one 2 s plain try after a Wi-Fi association answered nothing, the update was skipped for the whole boot): three TLS tries with growing deadlines, a short pause between them, then plain HTTP */
			u32 tst = 0;
			int att;
			for (att = 0; att < 3; att++) {
				u32 lf = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : 20000u, d2 = deadline_ms * (u32)(att + 1);
				if (d2 > lf) d2 = lf;
				if (d2 < 800u) break;
				ota_log("GET %s via tls %u.%u.%u.%u:%u host %s deadline %lu ms (try %d of 3)", path, IPQ(tip), (unsigned)MSOTA_TLS_PORT, host, (unsigned long)d2, att + 1);
				if (ota_tls_get(tip, path, max, d2, body, blen, &tst) == 0) {
					*status = tst;
					ota_ip_override = tip;
					ota_cache_after_tls(tip, baked);
					g_get_rc = 0; g_get_status = tst;
					return 0;
				}
				ota_log("tls: failed (%s)", g_tls_why);
				*body = NULL; *blen = 0; *status = 0;
				usleep(400 * 1000);
			}
			{   /* the other addresses, one pinned-key try each: ota.ip, then the DNS answer (looked up now, once per run) */
				u32 lf = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : 20000u;
				ota_dns_fallback(lf);
				n = (u32)mssp_order(ota_ip_override, baked, ota_cache_ip, ota_dns_ip, cand, how);
				for (i = 0; i < n; i++) {
					u32 d2 = deadline_ms * 2u;
					if (cand[i] == tip) continue;
					lf = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : 20000u;
					if (d2 > lf) d2 = lf;
					if (d2 < 800u) { ota_log("tls: no time left for %s", how[i]); break; }
					ota_log("GET %s via tls %s %u.%u.%u.%u:%u host %s deadline %lu ms (fallback)", path, how[i], IPQ(cand[i]), (unsigned)MSOTA_TLS_PORT, host, (unsigned long)d2);
					if (ota_tls_get(cand[i], path, max, d2, body, blen, &tst) == 0) {
						*status = tst;
						ota_ip_override = cand[i];
						ota_log("server: %u.%u.%u.%u proved the pinned key (%s): used first for the rest of this run", IPQ(cand[i]), how[i]);
						ota_cache_after_tls(cand[i], baked);
						g_get_rc = 0; g_get_status = tst;
						return 0;
					}
					ota_log("tls: failed (%s)", g_tls_why);
					*body = NULL; *blen = 0; *status = 0;
				}
			}
			ota_log("tls: three tries failed: falling back to plain signed HTTP");
			ota_tls_dead = 1;
		}
	} else if (MS_OTA_NTLSPIN == 0 && !ota_tls_dead) { ota_tls_dead = 1; ota_log("tls: no pin built into this shell (tools/release/ota_tls_pin.txt is empty): plain signed HTTP"); }
	for (i = 0; i < n; i++) {
		u32 left = g_boot_ctx ? (past(net_t0, g_boot_ms) ? 0u : g_boot_ms - (u32)(now_ms() - net_t0)) : (20000u > (u32)(now_ms() - t0) ? 20000u - (u32)(now_ms() - t0) : 0u), dl = deadline_ms;
		if (!cand[i]) continue;
		if (dl > left) dl = left;
		if (dl < 400u) { ota_log("GET %s: no time left for %s", path, how[i]); break; }
		ota_ip_override = cand[i];
		ota_log("GET %s via %s %u.%u.%u.%u:%u host %s deadline %lu ms", path, how[i], IPQ(cand[i]), (unsigned)port, host, (unsigned long)dl);
		rc = ota_get_raw(path, max, dl, body, blen, status);
		ota_log("  -> rc %d http %lu body %lu bytes in %lu ms", rc, (unsigned long)*status, (unsigned long)*blen, (unsigned long)(now_ms() - t0));
		if (rc != -1) break;                                         /* it connected (whatever the server then said): this address stays */
	}
	if (rc == -1 && !ota_url_used) ota_ip_override = 0;              /* nothing connected: the next request tries them all again */
	if (rc == 0 && !ota_url_used && ota_dns_ip && ota_ip_override == ota_dns_ip && !ota_ip_saved) { ota_ip_saved = 1; ota_log("dns: %u.%u.%u.%u answered plain HTTP: not remembered in ota.ip (only the pinned key proves an address)", IPQ(ota_dns_ip)); }
	g_get_rc = rc; g_get_status = *status;
	return rc;
}

static int ota_get_raw(const char *path, u32 max, u32 deadline_ms, u8 **body, u32 *blen, u32 *status)
{
	struct sockaddr_in sa;
	u32 ip, t0 = now_ms(), have = 0, hdr_end = 0, clen = 0;
	u16 port;
	char host[64], req[400];
	u8 *buf = NULL;
	u32 cap = 4096;
	s32 s, res, fl;
	int rc = -1;
	ota_server(&ip, &port, host, sizeof(host));
	*body = NULL; *blen = 0; *status = 0;
	s = net_socket(PF_INET, SOCK_STREAM, 0);
	if (s < 0) return -1;
	fl = net_fcntl(s, F_GETFL, 0);
	if (fl < 0 || net_fcntl(s, F_SETFL, fl | 4) < 0) { net_close(s); return -1; }
	memset(&sa, 0, sizeof sa);
	sa.sin_family = PF_INET; sa.sin_len = sizeof sa; sa.sin_port = htons(port); sa.sin_addr.s_addr = htonl(ip);
	for (;;) {                                                       /* connect, polled: never a blocking call */
		if (past(t0, deadline_ms)) { net_close(s); return -1; }
		res = net_connect(s, (struct sockaddr *)&sa, sizeof sa);
		if (res >= 0 || res == -EISCONN) break;
		if (res == -EINPROGRESS || res == -EALREADY) { usleep(20 * 1000); continue; }
		net_close(s); return -1;
	}
	snprintf(req, sizeof req, "GET %s HTTP/1.1\r\nHost: %s\r\nUser-Agent: multishine-nintendont\r\nAccept: */*\r\nConnection: close\r\n\r\n", path, host);
	{
		u32 sent = 0, n = (u32)strlen(req);
		while (sent < n) {
			if (past(t0, deadline_ms)) { net_close(s); return -1; }
			res = net_write(s, req + sent, (int)(n - sent));
			if (res == 0 || res == -EAGAIN || res == -56) { usleep(20 * 1000); continue; }
			if (res < 0) { net_close(s); return -1; }
			sent += (u32)res;
		}
	}
	buf = (u8 *)memalign(32, cap);
	if (!buf) { net_close(s); return -3; }
	for (;;) {
		if (hdr_end && have >= hdr_end + clen) { rc = 0; break; }
		if (past(t0, deadline_ms)) { rc = -1; break; }
		if (have + 1024 > cap) {                                      /* grow: headers first, then exactly what Content-Length says (never more than max) */
			u32 want = hdr_end ? hdr_end + clen : cap * 2;
			u8 *nb;
			if (want < have + 1024) want = have + 1024;
			if (hdr_end && clen > max) { rc = -3; break; }
			if (want > max + 2048) want = max + 2048;
			if (want <= cap) { rc = -3; break; }
			nb = (u8 *)memalign(32, want);
			if (!nb) { rc = -3; break; }
			memcpy(nb, buf, have); free(buf); buf = nb; cap = want;
		}
		res = net_read(s, buf + have, (int)(cap - have > 4096 ? 4096 : cap - have));
		if (res == -EAGAIN || res == -56) { usleep(10 * 1000); continue; }
		if (res == 0) {                                               /* the peer closed: fine only if everything arrived */
			if (hdr_end && have >= hdr_end + clen) { rc = 0; break; }
			usleep(10 * 1000); continue;
		}
		if (res < 0) { rc = -1; break; }
		have += (u32)res;
		if (!hdr_end) {
			mw2_u32 st = 0, cl = 0xFFFFFFFFu, he = 0;
			if (msota_http_head(buf, have, &st, &cl, &he) == 0) {
				hdr_end = he; *status = st; clen = cl;
				if (*status != 200 || clen == 0xFFFFFFFFu || clen == 0) { rc = -2; break; }
				if (clen > max) { rc = -3; break; }
			}
		}
	}
	net_close(s);
	if (rc == 0) {
		u8 *out = (u8 *)memalign(32, (clen + 31u) & ~31u);
		if (!out) rc = -3;
		else { memcpy(out, buf + hdr_end, clen); *body = out; *blen = clen; }
	}
	free(buf);
	return rc;
}

#define parse_after(s, k) ((unsigned long)msota_json_uint((s), (k)))

/* ---- the two updatable kinds: the kernel (krn) and the shell (shl) -------------------------------------------------------------------------------------------------------- */
struct ota_kind {
	const char *name, *route, *bin, *knew, *bak;
	u32 max_file;
	int (*check)(const u8 *buf, u32 len, u32 min_seq, u32 *seq);
};

static int check_krn(const u8 *buf, u32 len, u32 min_seq, u32 *seq)
{
	struct msota_kernel k;
	int r = msota_check(buf, len, ms_ota_pubs, MS_OTA_NPUB, min_seq, &k);
	if (r == MSOTA_OK) *seq = k.seq;
	return r;
}

static int check_shl(const u8 *buf, u32 len, u32 min_seq, u32 *seq)
{
	struct msota_shell k;
	int r = msota_check_shell(buf, len, ms_ota_pubs, MS_OTA_NPUB, min_seq, &k);
	if (r == MSOTA_OK) *seq = k.seq;
	return r;
}

static const struct ota_kind KIND_KRN = { "kernel", "krn", MSOTA_KBIN, MSOTA_KNEW, MSOTA_KBAK, MSOTA_MAX_FILE, check_krn };
static const struct ota_kind KIND_SHL = { "shell", "shl", MSOTA_SHL_BIN, MSOTA_SHL_NEW, MSOTA_SHL_BAK, MSOTA_MAX_SHELL_FILE, check_shl };

enum { OU_UPTODATE = 0, OU_INSTALLED = 1, OU_NONET = -1, OU_NOANSWER = -2, OU_DOWNLOAD = -3, OU_REFUSED = -4, OU_WRITE = -5, OU_SKIPPED = -6, OU_FULL = -7, OU_VERIFY = -8 };
static char g_why[72];                     /* the last install failure in words, shown on the Update and About screens */
static u32 g_last_size;                    /* the size the server announced for the file about to be downloaded */

/* is a newer file of this kind published?  0 = no, >0 = the sequence, <0 = could not ask.  *size = its size */
static long ota_latest(const struct ota_kind *K, u32 have, u32 deadline_ms, u32 *size)
{
	char path[96];
	u8 *b = NULL;
	u32 n = 0, status = 0;
	unsigned long latest;
	snprintf(path, sizeof path, "/v1/update/%s/latest?have=%lu", K->route, (unsigned long)have);
	if (ota_get(path, 1024, deadline_ms, &b, &n, &status) != 0) { ota_log("  %s have %lu: no answer (rc %d http %lu)", K->route, (unsigned long)have, g_get_rc, (unsigned long)g_get_status); return -1; }
	((char *)b)[n < 1023 ? n : 1023] = 0;
	latest = parse_after((const char *)b, "\"latest\":");
	if (size) *size = (u32)parse_after((const char *)b, "\"size\":");
	g_contact = 1;
	g_last_size = size ? *size : 0;
	ota_log("  %s have %lu -> latest %lu size %lu", K->route, (unsigned long)have, latest, (unsigned long)(size ? *size : 0));
	free(b);
	return (long)latest;
}


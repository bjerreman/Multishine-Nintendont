/* the read speed test (Start on the Diagnostics page): what the stock Melee image reads at from SD and from USB, and what the disc in the drive reads at (inner and outer part of the disc).  A few MiB each (ms_speed.h),
   result lines on screen and in ota.log; B stops it.  Nothing is written anywhere. */
struct spd_row { char name[24]; unsigned kibs, i4, l4, i32, l32; char note[48]; };      /* sequential KiB/s; random reads/s and average us per read at 4 KiB and 32 KiB */
static unsigned g_spd_seed = 12345;
static void spd_random(struct spd_row *w, FIL *f, int disc)                       /* scattered reads: from the open file, or from the disc in the drive (2 KiB aligned) */
{
	u8 *b = (u8 *)memalign(32, MSSPD_LARGE);
	const unsigned long size = disc ? 1459978240ul : (unsigned long)f_size(f);       /* the stock Melee image is 1,459,978,240 bytes */
	int pass;
	if (!b) return;
	for (pass = 0; pass < 2; pass++) {
		const unsigned len = pass ? MSSPD_LARGE : MSSPD_SMALL;
		unsigned long n = 0;
		u32 t0 = now_ms(), ms;
		UINT got;
		while (n < MSSPD_RND_MAX && now_ms() - t0 < MSSPD_RND_MS) {
			const unsigned long off = msspd_rnd_off(&g_spd_seed, size, len, 2048);
			if (disc) ReadRealDisc(b, (u32)off, len, DIP_CMD_NORMAL);
			else if (f_lseek(f, off) != FR_OK || f_read(f, b, len, &got) != FR_OK || got == 0) break;
			n++;
			if (ds_stop(0)) break;
		}
		ms = now_ms() - t0;
		if (pass) { w->i32 = msspd_iops(n, ms); w->l32 = msspd_lat_us(n, ms); }
		else { w->i4 = msspd_iops(n, ms); w->l4 = msspd_lat_us(n, ms); }
	}
	free(b);
}
static void spd_file(struct spd_row *w, const char *path)
{
	FIL f;
	u8 *b;
	unsigned long total = 0;
	u32 t0, ms;
	UINT got;
	if (f_open_char(&f, path, FA_READ | FA_OPEN_EXISTING) != FR_OK) { snprintf(w->note, sizeof w->note, "cannot open the image"); return; }
	b = (u8 *)memalign(32, MSSPD_CHUNK);
	if (!b) { f_close(&f); snprintf(w->note, sizeof w->note, "no memory"); return; }
	t0 = now_ms();
	while (total < MSSPD_MAX_BYTES && now_ms() - t0 < MSSPD_MAX_MS) {
		if (f_read(&f, b, MSSPD_CHUNK, &got) != FR_OK || got == 0) break;
		total += got;
		if (ds_stop(0)) break;
	}
	ms = now_ms() - t0;
	free(b);
	w->kibs = msspd_kibs(total, ms);
	spd_random(w, &f, 0);
	f_close(&f);
}
static unsigned spd_disc_seq(u32 offset)
{
	u8 *b = (u8 *)memalign(32, MSSPD_CHUNK);
	unsigned long total = 0;
	u32 t0, ms;
	if (!b) return 0;
	t0 = now_ms();
	while (total < MSSPD_MAX_BYTES && now_ms() - t0 < MSSPD_MAX_MS) {
		ReadRealDisc(b, offset + (u32)total, MSSPD_CHUNK, DIP_CMD_NORMAL);
		total += MSSPD_CHUNK;
		if (ds_stop(0)) break;
	}
	ms = now_ms() - t0;
	free(b);
	return msspd_kibs(total, ms);
}
static void spd_draw(const struct spd_row *r, int n, const char *status)
{
	int i, y = MENU_POS_Y + 36;
	ClearScreen();
	ms_title("Read speed test");
	y += 20 * wrap_text(MENU_POS_X, y, "Figures only, no verdict: how fast the game image reads from each place.", BLACK, 590, 20, DEFAULT_SIZE);
	y += 8;
	for (i = 0; i < n; i++) {
		char v[24];
		msspd_fmt(v, sizeof v, r[i].kibs);
		PrintFormat(DEFAULT_SIZE, BLACK, MENU_POS_X, y, "%s", r[i].name);
		PrintFormat(DEFAULT_SIZE, BLACK, MENU_POS_X + 260, y, "Sequential %s", v);
		if (r[i].i4) {
			PrintFormat(14, 0x98ABC2FF, MENU_POS_X + 24, y + 20, "Random 4 KB: %u reads/s, %u.%u ms each", r[i].i4, r[i].l4 / 1000, (r[i].l4 % 1000) / 100);
			PrintFormat(14, 0x98ABC2FF, MENU_POS_X + 24, y + 36, "Random 32 KB: %u reads/s, %u.%u ms each", r[i].i32, r[i].l32 / 1000, (r[i].l32 % 1000) / 100);
			y += 62;
		} else if (r[i].note[0]) { PrintFormat(14, 0x98ABC2FF, MENU_POS_X + 24, y + 20, "%.64s", r[i].note); y += 44; }
		else y += 26;
	}
	if (status && status[0]) PrintFormat(DEFAULT_SIZE, BLACK, MENU_POS_X, y + 8, "%s", status);
	ms_foot(0, "B", "Back", "A", "Run again", NULL);
	UpdateScreen();
	ClearScreen();
}
static void ms_speed_screen(void)
{
	struct spd_row r[4];
	u64 delay = 0;
	int n, run = 1, usb;
	if (!devices[DEV_SD]) MountDevice(DEV_SD);
	for (;;) {
		if (run) {
			run = 0;
			n = 0;
			memset(r, 0, sizeof r);
			for (usb = 0; usb < 2; usb++) {
				struct spd_row *w = &r[n];
				if (!devices[usb ? DEV_USB : DEV_SD]) continue;
				snprintf(w->name, sizeof w->name, "%s", usb ? "USB drive" : "SD card");
				n++;
				spd_draw(r, n, "Reading...");
				if (!g_dev[usb].first[0]) scan_dev(usb);
				if (!g_dev[usb].first[0]) snprintf(w->note, sizeof w->note, "no stock Melee image to read");
				else spd_file(w, g_dev[usb].first);
				ota_log("speed: %s seq %u KiB/s, rnd4k %u/s %u us, rnd32k %u/s %u us%s%s", w->name, w->kibs, w->i4, w->l4, w->i32, w->l32, w->note[0] ? " " : "", w->note);
			}
			if (msst_drive_probe_allowed(IsWiiU(), isWiiVC, file_exists("sd:/multishine/no_drive_probe"))) {
				struct spd_row *w = &r[n];
				snprintf(w->name, sizeof w->name, "Disc in the drive");
				n++;
				spd_draw(r, n, "Reading the disc...");
				if (!drive_probe()) snprintf(w->note, sizeof w->note, "no stock Melee disc in the drive");
				else {
					const unsigned in = spd_disc_seq(0x100000u), out = spd_disc_seq(0x40000000u);
					w->kibs = in;                                                       /* the inner part; the outer one goes in the log */
					spd_random(w, NULL, 1);
					ota_log("speed: disc inner %u KiB/s, outer %u KiB/s", in, out);
				}
				ota_log("speed: disc seq %u KiB/s, rnd4k %u/s %u us, rnd32k %u/s %u us %s", w->kibs, w->i4, w->l4, w->i32, w->l32, w->note);
			}
			spd_draw(r, n, n ? "Done. The same figures are in the log." : "No place to test: no SD card, USB drive or disc drive.");
			delay = ticks_to_millisecs(gettime()) + 400;
		}
		VIDEO_WaitVSync();
		FPAD_Update();
		if (delay > ticks_to_millisecs(gettime())) continue;
		if (FPAD_OK(0)) run = 1;
		else if (FPAD_Cancel(0)) break;
	}
	ClearScreen();
}


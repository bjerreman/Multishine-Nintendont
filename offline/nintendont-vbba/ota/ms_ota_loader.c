/* which card the set-up makes: the slots are sensed only when there is no virtual card yet and the console has GameCube card ports; the result, the route and why go to ota.log and on screen */
static void setup_route(const struct msst_facts *f)
{
	struct mscr_slot a, b;
	struct mscr_decision d;
	const int con = mscr_console(IsWiiU(), isWiiVC);
	char sa[48], sb[48];
	int route;
	memset(&a, 0, sizeof a); memset(&b, 0, sizeof b);
	if (mscr_probe_allowed(con) && !f->card) { card_probe(0, &a); card_probe(1, &b); }
	d = mscr_decide(con, &a, f->card, mscr_full(0));
	route = d.route == MSCR_R_ASK ? setup_ask(&d, &a, &b) : d.route;
	su.phys = route == MSCR_R_PHYS;
	mscr_route_text(su.route, sizeof su.route, &d, route);
	if (su.phys) { mscr_slot_text(sa, sizeof sa, 'A', &a); snprintf(su.info, sizeof su.info, "%s. About %u needed today (can change with updates).", sa, mscr_full(0)); }
	else snprintf(su.info, sizeof su.info, "Virtual card: %u blocks. About %u needed today (can change with updates).", MSCR_VCARD_BLOCKS, mscr_full(0));
	mscr_slot_text(sa, sizeof sa, 'A', &a); mscr_slot_text(sb, sizeof sb, 'B', &b);
	ota_log("setup: memory card sense: %s; %s; console %d; route %s: %s", mscr_probe_allowed(con) && !f->card ? sa : "slots not sensed", mscr_probe_allowed(con) && !f->card ? sb : "", con, su.phys ? "slot A" : "virtual card", su.route);
}

/* run one step with the existing code; 0 = done, -1 = failed (su.det holds the plain reason) */
static int setup_step(unsigned step, const struct msst_facts *f)
{
	static char discs[MSPK_MAX_PICK][MSGAMES_DIR_LEN];
	struct msst_facts g;
	unsigned seen = 0;
	int line = 5, n;
	(void)f;
	su.det[0] = 0;
	if (step == MSST_NET) {
		const int r = ota_net_up_retry(30000);
		if (r != 0) { ota_log("setup: network check failed (%d)", r); setup_fail(msst_fail_text(MSST_NET)); ota_net_down(); return -1; }
		return 0;
	}
	if (step == MSST_ISO) {
		n = find_discs(discs, MSPK_MAX_PICK, &seen);
		if (n > 0) return 0;
		if (g_drive) { snprintf(su.det, sizeof su.det, "%s", msst_setup_iso_drive_text()); su.dcol = MAROON; return -1; }       /* only a disc in the drive: the builder reads image FILES through FatFs, not the DVD drive */
		msst_none_line(su.det, sizeof su.det, "SD", seen, g_fd_near, g_fd_near_size, g_fd_stopped, g_drive_ok, 0);
		su.dcol = MAROON;
		return -1;
	}
	if (step == MSST_DL) {
		g_setup_quiet = 1; g_last_bad[0] = 0;
		card_download(&line, 1);
		g_setup_quiet = 0;
		probe_files(&g);
		if (g.crd && g.pack) { su.det[0] = 0; return 0; }
		setup_fail(g_last_bad[0] ? g_last_bad : msst_fail_text(MSST_DL));
		return -1;
	}
	if (su.phys) {                                                         /* the memory card in slot A: its own screen (the free blocks, the A-confirm that names our files before any erase) */
		int r;
		g_setup_have_files = 1; g_last_bad[0] = 0;
		r = card_physical(0);
		g_setup_have_files = 0;
		if (r == 0) { write_file(MSPHYS_MARK, (const u8 *)"1", 1); FlushDevices(); ota_log("setup: installed on the memory card in slot A"); return 0; }
		setup_fail(g_last_bad[0] ? g_last_bad : "The memory card in slot A was not changed.");
		return -1;
	}
	g_setup_quiet = 1; g_setup_have_files = 1; g_last_bad[0] = 0;
	card_virtual(2);
	g_setup_have_files = 0; g_setup_quiet = 0;
	slotb_ensure(1);                                                       /* the backup card in slot B, quietly: no row, no mark, never a failure of the set-up */
	probe_files(&g);
	if (g.card && g.sysfiles) { su.det[0] = 0; return 0; }
	setup_fail(g_last_bad[0] ? g_last_bad : msst_fail_text(MSST_CARD));
	return -1;
}

/* the whole set-up; 1 = finished and the player pressed A (Launch), 0 = Back */
static int ms_setup(void)
{
	unsigned done = 0;
	memset(&su, 0, sizeof su);
	su_on = 1;
	{
		struct msst_facts f0;
		probe_files(&f0);
		if (msst_plan(&f0) & MSST_CARD) setup_route(&f0);              /* a card is to be made: which one (no card sensed = the virtual card, no question) */
	}
	for (;;) {
		struct msst_facts f;
		unsigned step;
		int rc;
		probe_files(&f);
		su.plan = su.phys ? msst_plan_phys(&f) : msst_plan(&f); su.done = done; su.failed = 0;
		step = msst_next(su.plan, done);
		if (!step) {
			int a;
			su.running = 0; su.state = 2; snprintf(su.det, sizeof su.det, "Multishine is ready."); su.dcol = 0x6FDC9CFF;
			setup_draw();
			a = ask_a_or_b();
			ota_net_down(); su_on = 0;
			return a;
		}
		su.running = step; su.state = 0;
		setup_draw();
		rc = setup_step(step, &f);
		su.running = 0;
		if (rc == 0) { done |= step; continue; }
		su.failed = step; su.state = 1;
		ota_log("setup: step %u failed: %s", step, su.det);
		setup_draw();
		if (!ask_a_or_b()) { ota_net_down(); su_on = 0; return 0; }
		su.det[0] = 0;
	}
}


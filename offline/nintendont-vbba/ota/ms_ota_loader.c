static int br_poll(void) { FPAD_Update(); return FPAD_Cancel(0) ? 1 : 0; }

extern int (*ms_disc_poll)(void);                        /* ms_disc_gate.c: the hooks of ms_disc_check_path (B stops it, the reason of a refusal) */
extern char ms_disc_why[96];
extern int ms_disc_aborted;

/* the picked file against the header test and the disc lock (the very check of a game start): 1 = stock, 0 = refused (why = the one-line reason), -1 = the player pressed B */
static int br_check(const char *path, char *why, unsigned wn)
{
	FIL f;
	UINT got = 0;
	u8 *h;
	unsigned long size = 0;
	int ok = 0, r;
	char id[7];
	mdl_u8 rev = 0;
	why[0] = 0;
	ClearScreen();
	ms_title("Browse for a game");
	put_c(200, DEFAULT_SIZE, 0xE3EDF7FF, "Checking the disc...");
	ms_foot(0, "B", "Stop", NULL);
	UpdateScreen();
	ClearScreen();
	h = (u8 *)memalign(32, 64);
	if (!h) { snprintf(why, wn, "not enough memory"); return 0; }
	memset(h, 0, 64);
	if (f_open_char(&f, path, FA_READ | FA_OPEN_EXISTING) != FR_OK) { free(h); snprintf(why, wn, "the file could not be opened"); return 0; }
	size = (unsigned long)f_size(&f);
	if (size == MDS_STOCK_SIZE && f_read(&f, h, 0x20, &got) == FR_OK && got == 0x20) ok = 1;
	f_close(&f);
	if (size != MDS_STOCK_SIZE) { free(h); msb_why_size(why, wn, size); ota_log("browse: %s size %lu: not the size of a Melee image", path, size); return 0; }
	if (!ok) { free(h); snprintf(why, wn, "the file could not be read"); return 0; }
	memcpy(id, h, 6); id[6] = 0;
	if (!msdl_header_ok((const mdl_u8 *)h, id, &rev)) { free(h); msb_why_header(why, wn, id); ota_log("browse: %s header %s revision %u: refused", path, id, (unsigned)rev); return 0; }
	free(h);
	ms_disc_poll = br_poll;
	r = gd_check(0, path, 0);
	ms_disc_poll = NULL;
	if (ms_disc_aborted) { ms_disc_aborted = 0; ota_log("browse: %s: check stopped by B", path); return -1; }
	if (r == 1) return 1;
	snprintf(why, wn, "%s", ms_disc_why[0] ? ms_disc_why : "this image is not accepted");
	ota_log("browse: %s refused by the disc lock: %s", path, why);
	return 0;
}

/* the file browser over SD (and USB when both are there).  -1 = back (nothing chosen); otherwise the device flag (0 SD / 1 USB) of the stock image the player picked: it is the game now (GamePath), the
   device slot g_dev[] holds it, *save = the config must be written, and every later search tries it first (g_chosen) */
static int file_browser(int dev, bool *save)
{
	struct msb_state *s = &g_br;
	const int both = devices[DEV_SD] && devices[DEV_USB];
	int redraw = 1;
	if (!devices[dev ? DEV_USB : DEV_SD]) dev = !dev;
	msb_open(s, &DS_FS, dev, both);
	for (;;) {
		int key = 0, r;
		VIDEO_WaitVSync();
		FPAD_Update();
		if (Shutdown) LoaderShutdown();
		if (redraw) { br_draw(s); redraw = 0; }
		if (FPAD_Up(0)) key = MSB_K_UP;
		else if (FPAD_Down(0)) key = MSB_K_DOWN;
		else if (FPAD_Left(0)) key = MSB_K_LEFT;
		else if (FPAD_Right(0)) key = MSB_K_RIGHT;
		else if (FPAD_OK(0)) key = MSB_K_A;
		else if (FPAD_Cancel(0)) key = MSB_K_B;
		else if (FPAD_Y(0)) key = MSB_K_Y;
		if (!key) continue;
		r = msb_key(s, key, &DS_FS);
		redraw = 1;
		if (r == MSB_R_LEAVE) return -1;
		if (r == MSB_R_PICK) {
			char why[96];
			const int v = br_check(s->pick, why, sizeof why);
			if (v < 0) msb_check_stopped(s);
			else if (msb_set_verdict(s, v == 1, why) == MSB_R_LOCKED) {
				struct sdev *d = &g_dev[s->usb];
				br_draw(s);                                                                     /* the green check on the file, for a moment */
				usleep(600 * 1000);
				snprintf(g_chosen, sizeof g_chosen, "%s", s->pick);
				d->nstock = 1; d->has_games = 1; snprintf(d->first, sizeof d->first, "%s", s->pick);
				g_drive = 0;
				if (pick_game(s->usb, s->pick)) *save = true;
				ota_log("browse: locked in %s", s->pick);
				return s->usb;
			}
		}
	}
}


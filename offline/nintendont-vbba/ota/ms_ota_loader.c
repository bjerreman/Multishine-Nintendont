static const char *kind_text(const struct ota_kind *K)      /* the words the player reads (the log keeps K->name) */
{
	return K == &KIND_KRN ? "game engine" : K == &KIND_SHL ? "loader" : K->name;
}
static int update_kind(const struct ota_kind *K, u32 have, int *line)
{
	long lat;
	u32 size = 0, got = 0;
	int r;
	sayf(line, BLACK, "Checking for a newer %s...", kind_text(K));
	lat = ota_latest(K, have, 8000, &size);
	if (lat < 0) { sayf(line, MAROON, "Could not reach the update server."); return OU_NOANSWER; }
	if (lat == 0) { sayf(line, BLACK, "The %s is up to date.", kind_text(K)); return OU_UPTODATE; }
	sayf(line, BLACK, "Update available: %s %lu", kind_text(K), (unsigned long)lat);
	sayf(line, BLACK, "Downloading...");
	r = ota_install(K, (u32)lat, have ? have : 1, 40000, NULL, &got);
	if (r == OU_INSTALLED) { char nm[24]; if (K == &KIND_SHL) inst_shell_seq = got;      /* the caller restarts into it (do_update) and the About result line says so */
		snprintf(nm, sizeof nm, "%s", kind_text(K)); if (nm[0] >= 'a' && nm[0] <= 'z') nm[0] = (char)(nm[0] - 32); sayf(line, BLACK, K == &KIND_SHL ? "%s %lu installed." : "%s %lu installed.", nm, (unsigned long)got); }
	else if (r == OU_DOWNLOAD) sayf(line, MAROON, "The download failed.");
	else if (r == OU_REFUSED) sayf(line, MAROON, "The download did not verify. It was not used.");
	else if (r == OU_FULL) sayf(line, MAROON, "%s.", g_why);
	else if (r == OU_VERIFY) sayf(line, MAROON, "The file could not be checked after writing. It was not used.");
	else sayf(line, MAROON, "Could not write to the SD card.");
	return r;
}

/* 0 = up to date, 1 = something installed (a shell restarts the app by itself; the kernel is used when a game starts), 2 = no network, 3 = could not check or install */
static int do_update(void)
{
	struct msota_state st;
	int line = 5, r, r2, res = 0;
	say_begin("Update");
	load_state(&st);
	sayf(&line, BLACK, "Multishine update (loader %lu, game engine %lu)", (unsigned long)shell_have(), (unsigned long)st.floor);
	if (!devices[DEV_SD]) MountDevice(DEV_SD);
	g_why[0] = 0;
	inst_shell_seq = 0;
	ota_log("manual check: kernel floor %lu, shell have %lu", (unsigned long)st.floor, (unsigned long)shell_have());
	if (ota_net_up_retry(30000) != 0) {
		sayf(&line, MAROON, "No network. Check the cable or the Wi-Fi settings.");
		sayf(&line, BLACK, "Multishine games are unaffected.");
		sayf(&line, BLACK, "Check Settings > Network, then try again.");
		ota_log("manual check: no network (init %d, status %d)", g_net_rc, g_net_st);
		ota_net_down();
		sleep(6);
		return 2;
	}
	r = update_kind(&KIND_KRN, st.floor, &line);
	if (r == OU_INSTALLED) {
		load_state(&st);
		st.pending = 0; st.fail = 0; st.active = 0;
		save_state(&st);
		res = 1;
	} else if (r != OU_UPTODATE) res = 3;
	r2 = update_kind(&KIND_SHL, shell_have(), &line);
	if (r2 == OU_INSTALLED) res = 1;
	else if (r2 != OU_UPTODATE && res == 0) res = 3;
	ota_net_down();
	FlushDevices();
	if (g_contact) chk_set(0);                                           /* the server answered: a back-off left by an earlier failed start is over */
	ota_log("manual check done: result %d (server contact %d)", res, g_contact);
	if (inst_shell_seq) ota_chain_after_check();                         /* a shell was installed: restart into it now (the same verified hand-over, through a clean IOS58 reload); returns only when refused */
	sleep(4);
	return res;
}


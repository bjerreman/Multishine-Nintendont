/* sdc25519: see sdc25519.h.  Field representation and carry order follow the public-domain ref10 design (D. J. Bernstein et al.);
   the straight-line multiply/square are generated by the project's other tooling (which also proves the int32/int64 headroom); point formulas are
   the standard extended-coordinate add-2008-hwcd-3 / dbl-2008-hwcd for a = -1; scalar reduction is the TweetNaCl modL. */
